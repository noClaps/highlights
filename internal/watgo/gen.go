// Options configure generated code.
type Options struct {
	Package string
	// MemFile is the embedded initial memory image file name.
	MemFile string
}

// Generate returns Go source for the module and its initial memory image.
func Generate(mod *Module, opts Options) (src string, mem []byte, err error) {
	err = catch(func() { src, mem = generate(mod, opts) })
	return
}

type value struct {
	expr    string
	typ     ValType
	isBool  bool // expr is a Go bool expression; typ is I32
	isConst bool
	c       uint64
	stable  bool // unaffected by later side effects
}

type label struct {
	goName  string
	watName string
	isLoop  bool
	result  ValType
	resTemp string
	used    bool
}

type fgen struct {
	mod         *Module
	fn          *Func
	out         strings.Builder
	depth       int
	stack       []value
	labels      []*label
	temps       []Local
	localName   map[string]string
	localType   map[string]ValType
	unreachable bool
	nlabel      int
}

func generate(mod *Module, opts Options) (string, []byte) {
	var sb strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&sb, format, args...) }
	w("// Code generated by internal/cmd/genengine from WAT sources. DO NOT EDIT.\n\n")
	w("package %s\n\n", opts.Package)
	w("import (\n\t_ \"embed\"\n\n\trt \"highlights/internal/wasmrt\"\n)\n\n")
	w("var _ = rt.B2u\n\n")

	end := 0
	for _, seg := range mod.Data {
		end = max(end, seg.Offset+len(seg.Data))
	}
	mem := make([]byte, end)
	for _, seg := range mod.Data {
		copy(mem[seg.Offset:], seg.Data)
	}
	w("//go:embed %s\nvar initMem string\n\n", opts.MemFile)
	w("// Pages is the initial memory size in Wasm pages.\nconst Pages = %d\n\n", mod.Pages)

	// imports
	var imports []*Func
	for _, f := range mod.Funcs {
		if f.Import != nil {
			imports = append(imports, f)
		}
	}
	w("// Imports holds the host functions the module imports.\ntype Imports struct {\n")
	for _, f := range imports {
		w("\t// %s.%s\n\t%s func(*Machine%s)%s\n", f.Import.Module, f.Import.Field, importField(f), paramTypes(f), resultType(f))
	}
	w("}\n\n")

	w("// Machine is one module instance.\ntype Machine struct {\n\tMem []byte\n\tImports Imports\n")
	for _, g := range mod.Globals {
		if g.Mutable {
			w("\t%s %s\n", g.GoName, g.Type.goType())
		}
	}
	w("}\n\n")
	for _, g := range mod.Globals {
		if !g.Mutable {
			w("const %s = %s\n", g.GoName, constLiteral(g.Type, g.Init))
		}
	}
	w("\n// New creates an instance with the initial memory and globals.\nfunc New() *Machine {\n\tm := &Machine{Mem: make([]byte, Pages*rt.PageSize)}\n\tcopy(m.Mem, initMem)\n")
	for _, g := range mod.Globals {
		if g.Mutable && g.Init != 0 {
			w("\tm.%s = %s\n", g.GoName, constLiteral(g.Type, g.Init))
		}
	}
	w("\treturn m\n}\n\n")

	// call_indirect table
	if len(mod.Table) > 0 {
		w("var table [%d]func(*Machine)\n\nfunc init() {\n\ttable = [...]func(*Machine){\n", len(mod.Table))
		for _, ref := range mod.Table {
			f := mod.FuncByRef[ref]
			if f == nil {
				failf("table references unknown function %s", ref)
			}
			if len(f.Params) != 0 || len(f.Results) != 0 {
				failf("table function %s must have type [] -> []", ref)
			}
			w("\t(*Machine).%s,\n", f.GoName)
		}
		w("}\n}\n\n")
	}

	for _, f := range imports {
		w("func (m *Machine) %s(%s)%s {\n\t", f.GoName, paramDecls(f), resultType(f))
		if len(f.Results) > 0 {
			w("return ")
		}
		var args []string
		for i := range f.Params {
			args = append(args, fmt.Sprintf("p%d", i))
		}
		w("m.Imports.%s(m%s)\n}\n\n", importField(f), prefixComma(args))
	}

	// exports
	var exportNames []string
	exportOf := map[string]*Func{}
	for _, f := range mod.Funcs {
		for _, e := range f.Exports {
			exportNames = append(exportNames, e)
			exportOf[e] = f
		}
	}
	sort.Strings(exportNames)
	for _, e := range exportNames {
		f := exportOf[e]
		w("// Export%s calls the %q export.\n", goIdent(e), e)
		w("func (m *Machine) Export%s(%s)%s {\n\t", goIdent(e), paramDecls(f), resultType(f))
		if len(f.Results) > 0 {
			w("return ")
		}
		var args []string
		for i := range f.Params {
			args = append(args, fmt.Sprintf("p%d", i))
		}
		w("m.%s(%s)\n}\n\n", f.GoName, strings.Join(args, ", "))
	}
	for _, g := range mod.Globals {
		for _, e := range g.Exports {
			if g.Mutable {
				w("// ExportGlobal%s reads the %q global.\nfunc (m *Machine) ExportGlobal%s() %s { return m.%s }\n\n", goIdent(e), e, goIdent(e), g.Type.goType(), g.GoName)
			} else {
				w("// ExportGlobal%s reads the %q global.\nfunc (m *Machine) ExportGlobal%s() %s { return %s }\n\n", goIdent(e), e, goIdent(e), g.Type.goType(), g.GoName)
			}
		}
	}

	for _, f := range mod.Funcs {
		if f.Import != nil {
			continue
		}
		g := &fgen{mod: mod, fn: f, localName: map[string]string{}, localType: map[string]ValType{}}
		sb.WriteString(g.genFunc())
	}
	return sb.String(), mem
}

func importField(f *Func) string {
	field := goIdent(f.Import.Field)
	var sb strings.Builder
	upper := true
	for _, r := range field {
		if r == '_' {
			upper = true
			continue
		}
		if upper && r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		upper = false
		sb.WriteRune(r)
	}
	return sb.String()
}

func prefixComma(args []string) string {
	if len(args) == 0 {
		return ""
	}
	return ", " + strings.Join(args, ", ")
}

func paramTypes(f *Func) string {
	var s string
	for _, p := range f.Params {
		s += ", " + p.Type.goType()
	}
	return s
}

func paramDecls(f *Func) string {
	var parts []string
	for i, p := range f.Params {
		parts = append(parts, fmt.Sprintf("p%d %s", i, p.Type.goType()))
	}
	return strings.Join(parts, ", ")
}

func resultType(f *Func) string {
	if len(f.Results) == 0 {
		return ""
	}
	return " " + f.Results[0].goType()
}

func constLiteral(t ValType, v uint64) string {
	switch t {
	case I32:
		return fmt.Sprintf("uint32(%d)", uint32(v))
	case I64:
		return fmt.Sprintf("uint64(%d)", v)
	}
	failf("no constant literal for %s", t)
	return ""
}

// ---- function bodies ----

func (g *fgen) line(format string, args ...any) {
	g.out.WriteString(strings.Repeat("\t", g.depth+1))
	fmt.Fprintf(&g.out, format, args...)
	g.out.WriteByte('\n')
}

func (g *fgen) newTemp(t ValType) string {
	name := fmt.Sprintf("t%d", len(g.temps))
	g.temps = append(g.temps, Local{name, t})
	return name
}

func (g *fgen) newBoolTemp() string {
	name := fmt.Sprintf("t%d", len(g.temps))
	g.temps = append(g.temps, Local{name, "bool"})
	return name
}

func (g *fgen) genFunc() string {
	f := g.fn
	var params []string
	for i, p := range f.Params {
		name := fmt.Sprintf("p%d", i)
		if p.Name != "" {
			name = "l_" + goIdent(p.Name[1:])
			g.localName[p.Name] = name
			g.localType[p.Name] = p.Type
		}
		g.localName[strconv.Itoa(i)] = name
		g.localType[strconv.Itoa(i)] = p.Type
		params = append(params, name+" "+p.Type.goType())
	}
	var localDecls []string
	for i, l := range f.Locals {
		idx := len(f.Params) + i
		name := fmt.Sprintf("v%d", idx)
		if l.Name != "" {
			name = "l_" + goIdent(l.Name[1:])
			g.localName[l.Name] = name
			g.localType[l.Name] = l.Type
		}
		g.localName[strconv.Itoa(idx)] = name
		g.localType[strconv.Itoa(idx)] = l.Type
		localDecls = append(localDecls, fmt.Sprintf("var %s %s", name, l.Type.goType()))
	}
	var result ValType
	if len(f.Results) > 0 {
		result = f.Results[0]
	}
	// the function body is the outermost branch target
	fnLabel := &label{goName: "", result: result}
	if result != "" {
		fnLabel.resTemp = g.newTemp(result)
	}
	g.labels = append(g.labels, fnLabel)
	g.genSeq(f.Body)
	if !g.unreachable && result != "" {
		v := g.pop()
		g.line("return %s", g.asValue(v))
	}
	g.labels = g.labels[:0]

	var sb strings.Builder
	name := f.Name
	if name == "" && len(f.Exports) > 0 {
		name = fmt.Sprintf("(export %q)", f.Exports[0])
	}
	if name != "" {
		fmt.Fprintf(&sb, "// %s is %s.\n", f.GoName, name)
	}
	fmt.Fprintf(&sb, "func (m *Machine) %s(%s)%s {\n", f.GoName, strings.Join(params, ", "), resultType(f))
	for _, d := range localDecls {
		sb.WriteString("\t" + d + "\n")
	}
	for _, t := range g.temps {
		typ := "bool"
		if t.Type != "bool" {
			typ = t.Type.goType()
		}
		fmt.Fprintf(&sb, "\tvar %s %s\n", t.Name, typ)
	}
	var uses []string
	for i := range f.Locals {
		uses = append(uses, g.localName[strconv.Itoa(len(f.Params)+i)])
	}
	for _, t := range g.temps {
		uses = append(uses, t.Name)
	}
	for _, u := range uses {
		fmt.Fprintf(&sb, "\t_ = %s\n", u)
	}
	sb.WriteString(g.out.String())
	if fnLabel.used {
		if result != "" {
			fmt.Fprintf(&sb, "Lreturn:\n\treturn %s\n", fnLabel.resTemp)
		} else {
			sb.WriteString("Lreturn:\n")
		}
	}
	if result != "" {
		sb.WriteString("\tpanic(rt.Trap(\"unreachable\"))\n")
	}
	sb.WriteString("}\n\n")
	return sb.String()
}

func (g *fgen) push(v value) { g.stack = append(g.stack, v) }

func (g *fgen) pop() value {
	if len(g.stack) == 0 {
		failf("%s: operand stack underflow", g.fn.GoName)
	}
	v := g.stack[len(g.stack)-1]
	g.stack = g.stack[:len(g.stack)-1]
	return v
}

// asValue renders v as a numeric expression.
func (g *fgen) asValue(v value) string {
	if v.isBool {
		if v.typ == I64 {
			return "rt.B2u64(" + v.expr + ")"
		}
		return "rt.B2u(" + v.expr + ")"
	}
	return v.expr
}

// asBool renders v as a Go condition.
func (g *fgen) asBool(v value) string {
	if v.isBool {
		return v.expr
	}
	if v.isConst {
		return strconv.FormatBool(v.c != 0)
	}
	return "(" + v.expr + " != 0)"
}

// spill evaluates pending operands into temporaries before a side effect.
func (g *fgen) spill() {
	for i, v := range g.stack {
		if v.stable || v.isConst {
			continue
		}
		var t string
		if v.isBool {
			t = g.newBoolTemp()
		} else {
			t = g.newTemp(v.typ)
		}
		g.line("%s = %s", t, v.expr)
		g.stack[i] = value{expr: t, typ: v.typ, isBool: v.isBool, stable: true}
	}
}

func (g *fgen) genSeq(nodes []*wat.Sexpr) {
	for _, n := range nodes {
		if g.unreachable {
			return
		}
		g.genInstr(n)
	}
}

func constValue(t ValType, c uint64) value {
	if t == I32 {
		c &= 0xffffffff
	}
	return value{expr: constLiteral(t, c), typ: t, isConst: true, c: c, stable: true}
}

func boolConst(b bool) value {
	return value{expr: strconv.FormatBool(b), typ: I32, isBool: true, isConst: true, c: b2u(b), stable: true}
}

func b2u(b bool) uint64 {
	if b {
		return 1
	}
	return 0
}

func (g *fgen) findLabel(ref string) (*label, int) {
	if ref == "" {
		failf("missing branch label")
	}
	if ref[0] >= '0' && ref[0] <= '9' {
		d, _ := strconv.Atoi(ref)
		i := len(g.labels) - 1 - d
		if i < 0 {
			failf("branch depth %d out of range", d)
		}
		return g.labels[i], i
	}
	for i := len(g.labels) - 1; i >= 0; i-- {
		if g.labels[i].goName != "" && g.labels[i].watName == ref {
			return g.labels[i], i
		}
	}
	failf("%s: unknown label %s", g.fn.GoName, ref)
	return nil, 0
}

func (g *fgen) gotoLabel(l *label) string {
	l.used = true
	if l.goName == "" {
		return "goto Lreturn"
	}
	return "goto " + l.goName
}

// branchValue assigns the branch value for a target that takes one.
func (g *fgen) branchValue(l *label, v value) string {
	if l.goName == "" {
		return fmt.Sprintf("%s = %s", l.resTemp, g.asValue(v))
	}
	return fmt.Sprintf("%s = %s", l.resTemp, g.asValue(v))
}

func splitInstr(n *wat.Sexpr) (head string, imms []string, operands []*wat.Sexpr) {
	head = n.Head()
	for _, part := range n.List[1:] {
		if part.IsList {
			operands = append(operands, part)
		} else {
			imms = append(imms, part.Atom)
		}
	}
	return
}

func (g *fgen) genInstr(n *wat.Sexpr) {
	if !n.IsList {
		failf("%s: unfolded instruction %q is unsupported", g.fn.GoName, n.Atom)
	}
	head := n.Head()
	switch head {
	case "block", "loop":
		g.genBlock(n, head == "loop")
		return
	case "if":
		g.genIf(n)
		return
	case "call_indirect":
		g.genCallIndirect(n)
		return
	}
	_, imms, operands := splitInstr(n)
	for _, op := range operands {
		g.genInstr(op)
		if g.unreachable {
			return
		}
	}
	g.apply(head, imms)
}

func (g *fgen) blockHeader(rest []*wat.Sexpr) (name string, result ValType, body []*wat.Sexpr) {
	if len(rest) > 0 && !rest[0].IsList && strings.HasPrefix(rest[0].Atom, "$") {
		name = rest[0].Atom
		rest = rest[1:]
	}
	for len(rest) > 0 && rest[0].IsList && (rest[0].Head() == "result" || rest[0].Head() == "type" || rest[0].Head() == "param") {
		switch rest[0].Head() {
		case "result":
			if len(rest[0].List) != 2 {
				failf("multi-value blocks are unsupported")
			}
			result = parseValType(rest[0].List[1].Atom)
		default:
			failf("block types other than a single result are unsupported")
		}
		rest = rest[1:]
	}
	return name, result, rest
}

func (g *fgen) newLabel(watName string, isLoop bool, result ValType) *label {
	g.nlabel++
	prefix := "B"
	if isLoop {
		prefix = "L"
	}
	l := &label{goName: fmt.Sprintf("%s%d", prefix, g.nlabel), watName: watName, isLoop: isLoop, result: result}
	if result != "" && !isLoop {
		l.resTemp = g.newTemp(result)
	}
	return l
}

func (g *fgen) genBlock(n *wat.Sexpr, isLoop bool) {
	name, result, body := g.blockHeader(n.List[1:])
	g.spill()
	l := g.newLabel(name, isLoop, result)
	var res string
	if result != "" {
		if isLoop {
			res = g.newTemp(result)
		} else {
			res = l.resTemp
		}
	}
	base := len(g.stack)
	if isLoop {
		// emitted unconditionally; unused loop labels are removed below
		g.line("%s:", l.goName)
	}
	g.labels = append(g.labels, l)
	mark := g.out.Len()
	_ = mark
	g.genSeq(body)
	g.labels = g.labels[:len(g.labels)-1]
	fallthroughReachable := !g.unreachable
	if fallthroughReachable && result != "" {
		v := g.pop()
		g.line("%s = %s", res, g.asValue(v))
	}
	if fallthroughReachable && len(g.stack) != base {
		failf("%s: block leaves %d values", g.fn.GoName, len(g.stack)-base)
	}
	g.stack = g.stack[:base]
	if isLoop {
		if !l.used {
			g.removeLabelLine(l.goName)
		}
		g.unreachable = !fallthroughReachable
	} else {
		if l.used {
			g.depth--
			g.line("%s:", l.goName)
			g.depth++
		}
		g.unreachable = !fallthroughReachable && !l.used
	}
	if result != "" && !g.unreachable {
		g.push(value{expr: res, typ: result, stable: true})
	}
}

// removeLabelLine drops an unused loop label, which Go rejects.
func (g *fgen) removeLabelLine(name string) {
	s := g.out.String()
	marker := "\n" + strings.Repeat("\t", 0)
	_ = marker
	needle := name + ":\n"
	i := strings.LastIndex(s, "\t"+needle)
	if i < 0 {
		failf("lost label %s", name)
	}
	// trim the indentation before the label as well
	j := i
	for j > 0 && s[j-1] == '\t' {
		j--
	}
	s = s[:j] + s[i+1+len(needle):]
	g.out.Reset()
	g.out.WriteString(s)
}

func (g *fgen) genIf(n *wat.Sexpr) {
	name, result, rest := g.blockHeader(n.List[1:])
	var thenArm, elseArm *wat.Sexpr
	var cond []*wat.Sexpr
	for _, part := range rest {
		switch {
		case part.IsList && part.Head() == "then" && thenArm == nil:
			thenArm = part
		case part.IsList && part.Head() == "else" && elseArm == nil:
			elseArm = part
		default:
			cond = append(cond, part)
		}
	}
	g.genSeq(cond)
	if g.unreachable {
		return
	}
	c := g.pop()
	g.spill()
	l := g.newLabel(name, false, result)
	base := len(g.stack)
	g.labels = append(g.labels, l)
	g.line("if %s {", g.asBool(c))
	g.depth++
	reachable := false
	if thenArm != nil {
		g.genSeq(thenArm.List[1:])
	}
	if !g.unreachable {
		reachable = true
		if result != "" {
			v := g.pop()
			g.line("%s = %s", l.resTemp, g.asValue(v))
		}
	}
	g.stack = g.stack[:base]
	g.unreachable = false
	g.depth--
	if elseArm != nil && len(elseArm.List) > 1 {
		g.line("} else {")
		g.depth++
		g.genSeq(elseArm.List[1:])
		if !g.unreachable {
			reachable = true
			if result != "" {
				v := g.pop()
				g.line("%s = %s", l.resTemp, g.asValue(v))
			}
		}
		g.stack = g.stack[:base]
		g.unreachable = false
		g.depth--
	} else {
		if result != "" {
			failf("%s: if with a result needs an else arm", g.fn.GoName)
		}
		reachable = true
	}
	g.line("}")
	g.labels = g.labels[:len(g.labels)-1]
	if l.used {
		g.line("%s:", l.goName)
	}
	g.unreachable = !reachable && !l.used
	if result != "" && !g.unreachable {
		g.push(value{expr: l.resTemp, typ: result, stable: true})
	}
}

func (g *fgen) genCallIndirect(n *wat.Sexpr) {
	var operands []*wat.Sexpr
	for _, part := range n.List[1:] {
		if !part.IsList {
			failf("call_indirect with a table or type index is unsupported")
		}
		switch part.Head() {
		case "type", "param", "result":
			if len(part.List) > 1 {
				failf("call_indirect signatures other than [] -> [] are unsupported")
			}
		default:
			operands = append(operands, part)
		}
	}
	for _, op := range operands {
		g.genInstr(op)
		if g.unreachable {
			return
		}
	}
	idx := g.pop()
	g.spill()
	g.line("table[%s](m)", g.asValue(idx))
}

func memOffset(imms []string) int {
	off := 0
	for _, imm := range imms {
		if strings.HasPrefix(imm, "offset=") {
			off = int(parseInt(imm[len("offset="):]))
		} else if !strings.HasPrefix(imm, "align=") {
			failf("unsupported memory immediate %q", imm)
		}
	}
	return off
}

func addrExpr(addr value, off int) string {
	if addr.isConst {
		return strconv.FormatUint(addr.c+uint64(off), 10)
	}
	if off == 0 {
		return "int(" + addr.expr + ")"
	}
	return fmt.Sprintf("int(%s)+%d", addr.expr, off)
}

type binOp struct {
	typ    ValType
	goOp   string // infix operator, or a helper call when it starts with "rt."
	isCmp  bool
	signed bool
	fold   func(a, b uint64) uint64
}

var binOps = map[string]binOp{}

func init() {
	for _, t := range []ValType{I32, I64} {
		mask := uint64(0xffffffff)
		width := uint64(32)
		bitsName := "32"
		if t == I64 {
			mask = ^uint64(0)
			width = 64
			bitsName = "64"
		}
		sx := func(x uint64) int64 {
			if t == I32 {
				return int64(int32(uint32(x)))
			}
			return int64(x)
		}
		p := string(t) + "."
		binOps[p+"add"] = binOp{typ: t, goOp: "+", fold: func(a, b uint64) uint64 { return (a + b) & mask }}
		binOps[p+"sub"] = binOp{typ: t, goOp: "-", fold: func(a, b uint64) uint64 { return (a - b) & mask }}
		binOps[p+"mul"] = binOp{typ: t, goOp: "*", fold: func(a, b uint64) uint64 { return (a * b) & mask }}
		binOps[p+"and"] = binOp{typ: t, goOp: "&", fold: func(a, b uint64) uint64 { return a & b }}
		binOps[p+"or"] = binOp{typ: t, goOp: "|", fold: func(a, b uint64) uint64 { return a | b }}
		binOps[p+"xor"] = binOp{typ: t, goOp: "^", fold: func(a, b uint64) uint64 { return a ^ b }}
		binOps[p+"shl"] = binOp{typ: t, goOp: "<<", fold: func(a, b uint64) uint64 { return (a << (b & (width - 1))) & mask }}
		binOps[p+"shr_u"] = binOp{typ: t, goOp: ">>", fold: func(a, b uint64) uint64 { return (a & mask) >> (b & (width - 1)) }}
		binOps[p+"shr_s"] = binOp{typ: t, goOp: ">>s", signed: true, fold: func(a, b uint64) uint64 { return uint64(sx(a)>>(b&(width-1))) & mask }}
		binOps[p+"rotl"] = binOp{typ: t, goOp: "rt.Rotl" + bitsName, fold: func(a, b uint64) uint64 {
			if t == I32 {
				return uint64(bits.RotateLeft32(uint32(a), int(b&31)))
			}
			return bits.RotateLeft64(a, int(b&63))
		}}
		binOps[p+"rotr"] = binOp{typ: t, goOp: "rt.Rotr" + bitsName, fold: func(a, b uint64) uint64 {
			if t == I32 {
				return uint64(bits.RotateLeft32(uint32(a), -int(b&31)))
			}
			return bits.RotateLeft64(a, -int(b&63))
		}}
		cmp := func(op string, signed bool, f func(a, b uint64) bool) binOp {
			return binOp{typ: t, goOp: op, isCmp: true, signed: signed, fold: func(a, b uint64) uint64 { return b2u(f(a, b)) }}
		}
		binOps[p+"eq"] = cmp("==", false, func(a, b uint64) bool { return a == b })
		binOps[p+"ne"] = cmp("!=", false, func(a, b uint64) bool { return a != b })
		binOps[p+"lt_u"] = cmp("<", false, func(a, b uint64) bool { return a < b })
		binOps[p+"gt_u"] = cmp(">", false, func(a, b uint64) bool { return a > b })
		binOps[p+"le_u"] = cmp("<=", false, func(a, b uint64) bool { return a <= b })
		binOps[p+"ge_u"] = cmp(">=", false, func(a, b uint64) bool { return a >= b })
		binOps[p+"lt_s"] = cmp("<", true, func(a, b uint64) bool { return sx(a) < sx(b) })
		binOps[p+"gt_s"] = cmp(">", true, func(a, b uint64) bool { return sx(a) > sx(b) })
		binOps[p+"le_s"] = cmp("<=", true, func(a, b uint64) bool { return sx(a) <= sx(b) })
		binOps[p+"ge_s"] = cmp(">=", true, func(a, b uint64) bool { return sx(a) >= sx(b) })
	}
}

func signedType(t ValType) string {
	if t == I32 {
		return "int32"
	}
	return "int64"
}

