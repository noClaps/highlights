// Options configure generated code.
type Options struct {
	Package string
	// MemFile is the embedded initial memory image file name.
	MemFile string
}

// Generate returns Go source for the module and its initial memory image.
func Generate(mod *Module, opts Options) (src string, mem []byte, err error) {
	err = catch(func() { src, mem = generate(mod, opts) })
	return
}

type value struct {
	expr    string
	typ     ValType
	isBool  bool // expr is a Go bool expression; typ is I32
	isConst bool
	c       uint64
	stable  bool // unaffected by later side effects
	// call is set for a call's result temporary: the statement that
	// assigned it
	call string
}

type label struct {
	goName  string
	watName string
	isLoop  bool
	isFunc  bool
	result  ValType
	resTemp string
	used    bool
	// a block whose body is just a loop ends where the loop does, so a
	// branch to it breaks out of that loop
	breaks *label
	// whether a branch breaks out of this loop
	broken bool
	// breakStmt, when set, is the statement that leaves this block
	breakStmt string
	// inline holds the short code after the block that a branch to it can
	// run in place, ending in its own branch; targets are the labels that
	// code branches to, resolved where the block is
	inline  []*wat.Sexpr
	targets []*label
}

type fgen struct {
	mod         *Module
	fn          *Func
	out         strings.Builder
	depth       int
	stack       []value
	labels      []*label
	temps       []Local
	localName   map[string]string
	localType   map[string]ValType
	unreachable bool
	nlabel      int
	terminalEnd int // output length after a top-level loop that never exits
	labelNames  map[string]bool
	dead        map[*wat.Sexpr]bool // stores whose value is never read
	// pendingInline is the inlinable code after the block being generated
	pendingInline []*wat.Sexpr
	inlineDepth   int
}

func generate(mod *Module, opts Options) (string, []byte) {
	var sb strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&sb, format, args...) }
	w("// Code generated by internal/cmd/genengine from WAT sources. DO NOT EDIT.\n\n")
	w("package %s\n\n", opts.Package)
	w("import (\n\t_ \"embed\"\n\n\trt \"highlights/internal/wasmrt\"\n)\n\n")

	end := 0
	for _, seg := range mod.Data {
		end = max(end, seg.Offset+len(seg.Data))
	}
	mem := make([]byte, end)
	for _, seg := range mod.Data {
		copy(mem[seg.Offset:], seg.Data)
	}
	w("//go:embed %s\nvar initMem string\n\n", opts.MemFile)
	w("// Pages is the initial memory size in Wasm pages.\nconst Pages = %d\n\n", mod.Pages)

	// imports
	var imports []*Func
	for _, f := range mod.Funcs {
		if f.Import != nil {
			imports = append(imports, f)
		}
	}
	w("// Imports holds the host functions the module imports.\ntype Imports struct {\n")
	for _, f := range imports {
		w("\t// %s implements %s.%s.\n\t%s func(*Machine%s)%s\n", importField(f), f.Import.Module, f.Import.Field, importField(f), paramTypes(f), resultType(f))
	}
	w("}\n\n")

	w("// Machine is one module instance.\ntype Machine struct {\n\tMem []byte\n\tImports Imports\n")
	for _, g := range mod.Globals {
		if g.Mutable {
			w("\t%s %s\n", g.GoName, g.Type.goType())
		}
	}
	w("}\n\n")
	for _, g := range mod.Globals {
		if !g.Mutable {
			w("// %s is the immutable global %s.\nconst %s %s = %s\n\n", g.GoName, globalLabel(g), g.GoName, g.Type.goType(), constLiteral(g.Type, g.Init))
		}
	}
	w("// New creates an instance with the initial memory and globals.\nfunc New() *Machine {\n\tm := &Machine{Mem: make([]byte, Pages*rt.PageSize)}\n\tcopy(m.Mem, initMem)\n")
	for _, g := range mod.Globals {
		if g.Mutable && g.Init != 0 {
			w("\tm.%s = %s\n", g.GoName, constLiteral(g.Type, g.Init))
		}
	}
	w("\treturn m\n}\n\n")

	// call_indirect table
	if len(mod.Table) > 0 {
		w("var table [%d]func(*Machine)\n\nfunc init() {\n\ttable = [...]func(*Machine){\n", len(mod.Table))
		for _, ref := range mod.Table {
			f := mod.FuncByRef[ref]
			if f == nil {
				failf("table references unknown function %s", ref)
			}
			if len(f.Params) != 0 || len(f.Results) != 0 {
				failf("table function %s must have type [] -> []", ref)
			}
			w("\t(*Machine).%s,\n", f.GoName)
		}
		w("}\n}\n\n")
	}

	for _, f := range imports {
		w("// %s calls the imported %s.%s.\nfunc (m *Machine) %s(%s)%s {\n\t", f.GoName, f.Import.Module, f.Import.Field, f.GoName, paramDecls(f), resultType(f))
		if len(f.Results) > 0 {
			w("return ")
		}
		var args []string
		for i := range f.Params {
			args = append(args, fmt.Sprintf("p%d", i))
		}
		w("m.Imports.%s(m%s)\n}\n\n", importField(f), prefixComma(args))
	}

	// exports
	var exportNames []string
	exportOf := map[string]*Func{}
	for _, f := range mod.Funcs {
		for _, e := range f.Exports {
			exportNames = append(exportNames, e)
			exportOf[e] = f
		}
	}
	sort.Strings(exportNames)
	// an export whose function has another name gets a method of its own
	for _, e := range exportNames {
		f := exportOf[e]
		name := pascal(e)
		if name == f.GoName {
			continue
		}
		if mod.used[name] {
			name = "Export" + name
		}
		mod.used[name] = true
		w("// %s calls the %q export.\n", name, e)
		w("func (m *Machine) %s(%s)%s {\n\t", name, paramDecls(f), resultType(f))
		if len(f.Results) > 0 {
			w("return ")
		}
		var args []string
		for i := range f.Params {
			args = append(args, fmt.Sprintf("p%d", i))
		}
		w("m.%s(%s)\n}\n\n", f.GoName, strings.Join(args, ", "))
	}

	// lookup tables for tools and tests
	w("// Funcs maps each named function without parameters or results to its\n// method.\nvar Funcs = map[string]func(*Machine){\n")
	for _, f := range mod.Funcs {
		if f.Import == nil && f.Name != "" && len(f.Params) == 0 && len(f.Results) == 0 {
			w("\t%q: (*Machine).%s,\n", f.Name, f.GoName)
		}
	}
	w("}\n\n")
	w("// CallExport calls an export with integer arguments. It reports false\n// for an unknown export or one with vector values.\nfunc (m *Machine) CallExport(name string, args []uint64) (uint64, bool) {\n\tswitch name {\n")
	for _, e := range exportNames {
		f := exportOf[e]
		scalar := true
		for _, p := range f.Params {
			if p.Type == V128 {
				scalar = false
			}
		}
		for _, r := range f.Results {
			if r == V128 {
				scalar = false
			}
		}
		if !scalar {
			continue
		}
		var args []string
		for i, p := range f.Params {
			args = append(args, fmt.Sprintf("%s(arg(args, %d))", p.Type.goType(), i))
		}
		call := fmt.Sprintf("m.%s(%s)", f.GoName, strings.Join(args, ", "))
		w("\tcase %q:\n", e)
		if len(f.Results) > 0 {
			w("\t\treturn uint64(%s), true\n", call)
		} else {
			w("\t\t%s\n\t\treturn 0, true\n", call)
		}
	}
	w("\t}\n\treturn 0, false\n}\n\nfunc arg(args []uint64, i int) uint64 {\n\tif i < len(args) {\n\t\treturn args[i]\n\t}\n\treturn 0\n}\n\n")

	for _, f := range mod.Funcs {
		if f.Import != nil {
			continue
		}
		g := &fgen{mod: mod, fn: f, localName: map[string]string{}, localType: map[string]ValType{}}
		sb.WriteString(g.genFunc())
	}
	return sb.String(), mem
}

func importField(f *Func) string { return pascal(f.Import.Field) }

func globalLabel(g *Global) string {
	if g.Name != "" {
		return g.Name
	}
	return fmt.Sprintf("(export %q)", g.Exports[0])
}

func prefixComma(args []string) string {
	if len(args) == 0 {
		return ""
	}
	return ", " + strings.Join(args, ", ")
}

func paramTypes(f *Func) string {
	var s string
	for _, p := range f.Params {
		s += ", " + p.Type.goType()
	}
	return s
}

func paramDecls(f *Func) string {
	var parts []string
	for i, p := range f.Params {
		parts = append(parts, fmt.Sprintf("p%d %s", i, p.Type.goType()))
	}
	return strings.Join(parts, ", ")
}

func resultType(f *Func) string {
	if len(f.Results) == 0 {
		return ""
	}
	return " " + f.Results[0].goType()
}

// constLiteral writes an untyped constant: decimal when small, hex when
// the value reads as a bit pattern.
func constLiteral(t ValType, v uint64) string {
	if t == I32 {
		v &= 0xffffffff
	}
	if v < 0x10000 {
		return strconv.FormatUint(v, 10)
	}
	return fmt.Sprintf("%#x", v)
}

// typedLiteral writes a constant with its type, where the context would
// otherwise give it another one.
func typedLiteral(t ValType, v uint64) string {
	return t.goType() + "(" + constLiteral(t, v) + ")"
}

// trimParens drops parentheses that enclose a whole expression.
func trimParens(expr string) string {
	for len(expr) >= 2 && expr[0] == '(' && expr[len(expr)-1] == ')' {
		depth := 0
		for i := 0; i < len(expr); i++ {
			switch expr[i] {
			case '(':
				depth++
			case ')':
				depth--
			case '"':
				return expr
			case '\'':
				// skip a rune literal such as '(' or '\''
				j := i + 1
				if j < len(expr) && expr[j] == '\\' {
					j++
				}
				i = j + 1
			}
			if depth == 0 && i < len(expr)-1 {
				return expr
			}
		}
		expr = expr[1 : len(expr)-1]
	}
	return expr
}

