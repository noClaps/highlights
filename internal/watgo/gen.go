var tempName = regexp.MustCompile(`^(t|p|v)\d+$`)

// ---- function bodies ----

func (g *fgen) line(format string, args ...any) {
	g.out.WriteString(strings.Repeat("\t", g.depth+1))
	fmt.Fprintf(&g.out, format, args...)
	g.out.WriteByte('\n')
}

func (g *fgen) newTemp(t ValType) string {
	name := fmt.Sprintf("t%d", len(g.temps))
	g.temps = append(g.temps, Local{name, t})
	return name
}

// dropTemp forgets the most recent temporary if it is name.
func (g *fgen) dropTemp(name string) {
	if n := len(g.temps); n > 0 && g.temps[n-1].Name == name {
		g.temps = g.temps[:n-1]
	}
}

func (g *fgen) newBoolTemp() string {
	name := fmt.Sprintf("t%d", len(g.temps))
	g.temps = append(g.temps, Local{name, "bool"})
	return name
}

// localGoName picks a Go name for a WAT local, avoiding Go's reserved
// words, the generated temporaries, and names taken in this function.
func (g *fgen) localGoName(wat string, fallback string, taken map[string]bool) string {
	name := fallback
	if wat != "" {
		name = camel(wat[1:])
		if alt, ok := localAlternatives[name]; ok {
			name = alt
		}
		if name == "" || goReserved[name] || tempName.MatchString(name) {
			name += "_"
		}
	}
	for base, n := name, 2; taken[name]; n++ {
		name = fmt.Sprintf("%s%d", base, n)
	}
	taken[name] = true
	return name
}

func (g *fgen) genFunc() string {
	f := g.fn
	taken := map[string]bool{}
	var params []string
	for i, p := range f.Params {
		name := g.localGoName(p.Name, fmt.Sprintf("p%d", i), taken)
		if p.Name != "" {
			g.localName[p.Name] = name
			g.localType[p.Name] = p.Type
		}
		g.localName[strconv.Itoa(i)] = name
		g.localType[strconv.Itoa(i)] = p.Type
		if g.boolParams[f.GoName][i] {
			params = append(params, name+" bool")
		} else {
			params = append(params, name+" "+p.Type.goType())
		}
	}
	var locals []Local
	for i, l := range f.Locals {
		idx := len(f.Params) + i
		name := g.localGoName(l.Name, fmt.Sprintf("v%d", idx), taken)
		if l.Name != "" {
			g.localName[l.Name] = name
			g.localType[l.Name] = l.Type
		}
		g.localName[strconv.Itoa(idx)] = name
		g.localType[strconv.Itoa(idx)] = l.Type
		if g.boolLocals[name] {
			locals = append(locals, Local{name, "bool"})
		} else {
			locals = append(locals, Local{name, l.Type})
		}
	}
	var result ValType
	if len(f.Results) > 0 {
		result = f.Results[0]
	}
	var fnResult ValType
	if len(f.Results) > 0 {
		fnResult = f.Results[0]
	}
	fnBody := nameLabels(explicitReturn(storeBlockResults(foldConstIfs(restoreEqz(f.Body), g.constOf)), fnResult))
	g.dead = deadSets(fnBody)
	// the function body is the outermost branch target: branching to it
	// returns
	g.labels = append(g.labels, &label{result: result, isFunc: true})
	g.genSeq(fnBody)
	if !g.unreachable && result != "" {
		v := g.pop()
		g.line("return %s", g.returned(v))
	}
	g.labels = g.labels[:0]
	body := strings.TrimSuffix(g.out.String(), "\treturn\n")
	loopEnds := g.terminalEnd == g.out.Len()
	body = tidyBody(body)
	body = collapseElseIf(body)
	body = dropEmptyIfs(body)
	body = outdentElse(body)
	body = switchChains(body)
	body = returnConditions(body)
	body = unlabelBranches(body)
	body = dropUnreadTemps(body, g.temps, g.pure)
	body = g.nameTemps(body, params, locals)

	var sb strings.Builder
	name := f.Name
	if name == "" && len(f.Exports) > 0 {
		name = fmt.Sprintf("(export %q)", f.Exports[0])
	}
	if name != "" {
		fmt.Fprintf(&sb, "// %s is %s.\n", f.GoName, name)
	}
	results := resultType(f)
	if g.boolFuncs[f.GoName] {
		results = " bool"
	}
	// a parameter the body never reads is blank
	blanked := slices.Clone(params)
	for i, p := range params {
		name, typ, _ := strings.Cut(p, " ")
		if !readsVar(body, name) {
			blanked[i] = "_ " + typ
		}
	}
	fmt.Fprintf(&sb, "func (m *Machine) %s(%s)%s {\n", f.GoName, combineParams(blanked), results)
	// one declaration per type, in first-use order; variables the body
	// never mentions are left out, and ones it only assigns are marked
	// used, as Go requires
	vars := slices.Concat(locals, g.temps)
	types := map[string]string{}
	for _, p := range params {
		name, typ, _ := strings.Cut(p, " ")
		types[name] = typ
	}
	for _, v := range vars {
		types[v.Name] = "bool"
		if v.Type != "bool" {
			types[v.Name] = v.Type.goType()
		}
	}
	body = g.declareAtFirstUse(body, vars, types)
	body = g.hoistSelects(body, types)
	body = switchChains(body)
	var order []string
	byType := map[string][]string{}
	var unused []string
	for _, v := range vars {
		if !regexp.MustCompile(`\b`+v.Name+`\b`).MatchString(body) || regexp.MustCompile(`(?m)^\t`+v.Name+` := `).MatchString(body) {
			continue
		}
		typ := types[v.Name]
		if _, ok := byType[typ]; !ok {
			order = append(order, typ)
		}
		byType[typ] = append(byType[typ], v.Name)
		if !readsVar(body, v.Name) {
			unused = append(unused, v.Name)
		}
	}
	for _, typ := range order {
		fmt.Fprintf(&sb, "\tvar %s %s\n", strings.Join(byType[typ], ", "), typ)
	}
	for _, u := range unused {
		fmt.Fprintf(&sb, "\t_ = %s\n", u)
	}
	// memory moves only when it grows, so a function that cannot make it
	// grow keeps it in a local
	if strings.Count(body, "m.Mem") > 1 && !g.mayGrow(body) && !regexp.MustCompile(`\bmem\b`).MatchString(body) {
		body = strings.ReplaceAll(body, "m.Mem", "mem")
		sb.WriteString("\tmem := m.Mem\n")
	}
	sb.WriteString(body)
	if result != "" && !endsTerminating(body) && !loopEnds {
		sb.WriteString("\tpanic(rt.Trap(\"unreachable\"))\n")
	}
	sb.WriteString("}\n\n")
	return sb.String()
}

var wordRe = regexp.MustCompile(`\bt\d+\b`)

// constOf evaluates a condition built from constants and immutable
// globals.
func (g *fgen) constOf(n *wat.Sexpr) (uint64, bool) {
	if !n.IsList || n.Head() == "" {
		return 0, false
	}
	head, imms, operands := splitInstr(n)
	args := make([]uint64, len(operands))
	for i, o := range operands {
		c, ok := g.constOf(o)
		if !ok {
			return 0, false
		}
		args[i] = c
	}
	switch {
	case head == "i32.const" && len(imms) == 1:
		v, err := strconv.ParseInt(imms[0], 0, 64)
		if err != nil {
			return 0, false
		}
		return uint64(uint32(v)), true
	case head == "global.get" && len(imms) == 1:
		gl := g.global(imms[0])
		if gl.Mutable || gl.Type != I32 {
			return 0, false
		}
		return gl.Init & 0xffffffff, true
	case head == "i32.eqz" && len(args) == 1:
		return b2u(args[0] == 0), true
	case head == "i32.eq" && len(args) == 2:
		return b2u(args[0] == args[1]), true
	case head == "i32.ne" && len(args) == 2:
		return b2u(args[0] != args[1]), true
	case head == "i32.and" && len(args) == 2:
		return args[0] & args[1], true
	case head == "i32.or" && len(args) == 2:
		return args[0] | args[1], true
	}
	return 0, false
}

// zeroOrOne reports a value known to be 0 or 1.
func zeroOrOne(v value) bool { return v.isBool || v.flag || (v.isConst && v.c <= 1) }

// returned renders a returned value: a condition when the function
// returns a bool, a number otherwise.
func (g *fgen) returned(v value) string {
	if !zeroOrOne(v) {
		g.nonBool = true
	}
	if g.boolFuncs[g.fn.GoName] {
		return trimParens(g.asBool(v))
	}
	return trimParens(g.asValue(v))
}

// tidyBody reprints expressions and folds single-use call temporaries.
func tidyBody(body string) string {
	var lines []string
	for _, l := range strings.Split(body, "\n") {
		// a statement may tidy into several lines, or none
		if t := tidyLine(l); t != "" || l == "" {
			lines = append(lines, strings.Split(t, "\n")...)
		}
	}
	for {
		uses := map[string]int{}
		for _, l := range lines {
			for _, w := range wordRe.FindAllString(l, -1) {
				uses[w]++
			}
		}
		folded := foldTemps(lines, uses)
		if len(folded) == len(lines) {
			break
		}
		lines = folded
	}
	// folding writes statements that tidy further
	var out []string
	for _, l := range lines {
		if t := tidyLine(l); t != "" || l == "" {
			out = append(out, strings.Split(t, "\n")...)
		}
	}
	return strings.Join(out, "\n")
}

// explicitReturn ends a function body with a return, so a block just
// before it can run the return in place of a jump to the end.
func explicitReturn(body []*wat.Sexpr, result ValType) []*wat.Sexpr {
	ret := &wat.Sexpr{Atom: "return"}
	if result == "" {
		return append(slices.Clone(body), &wat.Sexpr{IsList: true, List: []*wat.Sexpr{ret}})
	}
	if n := len(body); n > 0 && isSimple(body[n-1]) && body[n-1].Head() != "return" {
		out := slices.Clone(body[:n-1])
		return append(out, &wat.Sexpr{IsList: true, List: []*wat.Sexpr{ret, body[n-1]}})
	}
	// a block whose value is the result returns it at each exit
	if n := len(body); n > 0 {
		if b := returnedBlock(body[n-1]); b != nil {
			return append(slices.Clone(body[:n-1]), b)
		}
	}
	return body
}

// collapseElseIf turns `} else {` holding a single if statement into
// `} else if`.
func collapseElseIf(body string) string {
	lines := strings.Split(body, "\n")
	for changed := true; changed; {
		changed = false
		for i := 0; i+1 < len(lines); i++ {
			trimmed := strings.TrimLeft(lines[i], "\t")
			if trimmed != "} else {" {
				continue
			}
			indent := lines[i][:len(lines[i])-len(trimmed)]
			inner := indent + "\t"
			if !strings.HasPrefix(lines[i+1], inner+"if ") || strings.HasPrefix(lines[i+1], inner+"\t") {
				continue
			}
			// the inner if ends at the first `}` at its own indentation
			k := i + 2
			for k < len(lines) && lines[k] != inner+"}" {
				if lines[k] != "" && !strings.HasPrefix(lines[k], inner) {
					k = len(lines)
				}
				k++
			}
			if k+1 >= len(lines) || lines[k+1] != indent+"}" {
				continue
			}
			out := append([]string{}, lines[:i]...)
			out = append(out, indent+"} else "+strings.TrimLeft(lines[i+1], "\t"))
			for _, l := range lines[i+2 : k] {
				out = append(out, strings.TrimPrefix(l, "\t"))
			}
			out = append(out, indent+"}")
			lines = append(out, lines[k+2:]...)
			changed = true
		}
	}
	return strings.Join(lines, "\n")
}

// dropEmptyIfs removes an if whose arms folding emptied, when its
// condition calls nothing.
func dropEmptyIfs(body string) string {
	lines := strings.Split(body, "\n")
	for changed := true; changed; {
		changed = false
		var out []string
		for i := 0; i < len(lines); i++ {
			l := lines[i]
			if i+1 < len(lines) {
				t := strings.TrimLeft(l, "\t")
				indent := l[:len(l)-len(t)]
				next := lines[i+1]
				// an empty else arm
				if t == "} else {" && next == indent+"}" {
					out = append(out, next)
					i++
					changed = true
					continue
				}
				if m := ifOpenRe.FindStringSubmatch(l); m != nil && next == indent+"}" && !methodCallRe.MatchString(m[2]) {
					i++
					changed = true
					continue
				}
			}
			out = append(out, l)
		}
		lines = out
	}
	return strings.Join(lines, "\n")
}

var methodCallRe = regexp.MustCompile(`\bm\.\w+\(`)

// outdentElse drops the else of an if whose first arm ends in a jump,
// moving the else arm's statements after the if.
func outdentElse(body string) string {
	lines := strings.Split(body, "\n")
	for changed := true; changed; {
		changed = false
		for i, l := range lines {
			t := strings.TrimLeft(l, "\t")
			if t != "} else {" || i == 0 {
				continue
			}
			indent := l[:len(l)-len(t)]
			last := strings.TrimLeft(lines[i-1], "\t")
			if lines[i-1] != indent+"\t"+last || !(last == "continue" || last == "break" || last == "return" ||
				strings.HasPrefix(last, "continue ") || strings.HasPrefix(last, "break ") || strings.HasPrefix(last, "return ") || strings.HasPrefix(last, "panic(")) {
				continue
			}
			// the if must start plainly, not as an else if, and its else
			// arm must end the statement
			start := i - 1
			for start >= 0 && !strings.HasPrefix(lines[start], indent+"if ") {
				if strings.HasPrefix(lines[start], indent+"}") || (lines[start] != "" && !strings.HasPrefix(lines[start], indent+"\t")) {
					start = -1
					break
				}
				start--
			}
			if start < 0 {
				continue
			}
			end := i + 1
			for end < len(lines) && lines[end] != indent+"}" {
				if lines[end] != "" && !strings.HasPrefix(lines[end], indent+"\t") {
					end = len(lines)
				}
				end++
			}
			if end >= len(lines) {
				continue
			}
			out := append([]string{}, lines[:i]...)
			out = append(out, indent+"}")
			for _, a := range lines[i+1 : end] {
				out = append(out, strings.TrimPrefix(a, "\t"))
			}
			lines = append(out, lines[end+1:]...)
			changed = true
			break
		}
	}
	return strings.Join(lines, "\n")
}

// returnConditions writes `if c { return true }; return false` as
// `return c`, and the negated form as `return !c`.
func returnConditions(body string) string {
	return boolReturnRe.ReplaceAllStringFunc(body, func(m string) string {
		sub := boolReturnRe.FindStringSubmatch(m)
		indent, cond, first, second := sub[1], sub[2], sub[3], sub[4]
		want := indent + "if " + cond + " {\n" + indent + "\treturn " + first + "\n" + indent + "}\n" + indent + "return " + second + "\n"
		if first == second || m != want {
			return m
		}
		if first == "false" {
			cond = negate(cond)
		}
		return indent + "return " + tidyExpr(cond) + "\n"
	})
}

var boolReturnRe = regexp.MustCompile(`(?m)^(\t+)if (.*) \{\n\t+return (true|false)\n\t+\}\n\t+return (true|false)\n`)

// switchChains writes an if with three or more arms as a switch with
// a case per condition. A chain whose arms hold an unlabeled break stays,
// since in a switch the break would leave the switch.
func switchChains(body string) string {
	lines := strings.Split(body, "\n")
	var out []string
	for i := 0; i < len(lines); i++ {
		m := ifOpenRe.FindStringSubmatch(lines[i])
		if m == nil {
			out = append(out, lines[i])
			continue
		}
		indent := m[1]
		heads := []int{i}
		end := -1
		breaks := false
		// the indentation of each for or switch open inside the arms, whose
		// breaks are their own
		var inner []string
		for k := i + 1; k < len(lines); k++ {
			l := lines[k]
			if l == indent+"}" {
				end = k
				break
			}
			if strings.HasPrefix(l, indent+"} else if ") || l == indent+"} else {" {
				heads = append(heads, k)
				continue
			}
			if l != "" && !strings.HasPrefix(l, indent+"\t") {
				break
			}
			trimmed := strings.TrimLeft(l, "\t")
			ind := l[:len(l)-len(trimmed)]
			switch {
			case strings.HasPrefix(trimmed, "for ") || strings.HasPrefix(trimmed, "switch "):
				inner = append(inner, ind)
			case len(inner) > 0 && l == inner[len(inner)-1]+"}":
				inner = inner[:len(inner)-1]
			case trimmed == "break" && len(inner) == 0:
				breaks = true
			}
		}
		if end < 0 || breaks || len(heads) < 3 {
			out = append(out, lines[i])
			continue
		}
		out = append(out, indent+"switch {")
		for j, h := range heads {
			switch {
			case j == 0:
				out = append(out, indent+"case "+m[2]+":")
			case lines[h] == indent+"} else {":
				out = append(out, indent+"default:")
			default:
				c := strings.TrimSuffix(strings.TrimPrefix(lines[h], indent+"} else if "), " {")
				out = append(out, indent+"case "+c+":")
			}
			next := end
			if j+1 < len(heads) {
				next = heads[j+1]
			}
			// arms keep their own chains, written in later passes
			if h+1 < next {
				out = append(out, switchChains(strings.Join(lines[h+1:next], "\n")))
			}
		}
		out = append(out, indent+"}")
		i = end
	}
	return strings.Join(out, "\n")
}

// unlabelBranches drops the label of a break or continue that names the
// innermost loop, where Go needs none: a continue may cross a switch, a
// break may not. Labels nothing names any more go too.
func unlabelBranches(body string) string {
	lines := strings.Split(body, "\n")
	type frame struct{ kind, label string }
	var stack []frame
	pending := ""
	for i, l := range lines {
		t := strings.TrimLeft(l, "\t")
		if m := labelLineRe.FindStringSubmatch(t); m != nil && m[1] != "default" {
			pending = m[1]
			continue
		}
		if m := branchLineRe.FindStringSubmatch(t); m != nil {
			for k := len(stack) - 1; k >= 0; k-- {
				f := stack[k]
				if f.kind == "for" {
					if f.label == m[2] {
						lines[i] = l[:len(l)-len(t)] + m[1]
					}
					break
				}
				if f.kind == "switch" && m[1] == "break" {
					break
				}
			}
		}
		if strings.HasPrefix(t, "}") {
			if len(stack) > 0 {
				stack = stack[:len(stack)-1]
			}
		}
		if strings.HasSuffix(t, "{") {
			kind := "block"
			switch {
			case strings.HasPrefix(t, "for ") || t == "for {":
				kind = "for"
			case strings.HasPrefix(t, "switch ") || strings.HasPrefix(t, "select "):
				kind = "switch"
			}
			stack = append(stack, frame{kind, pending})
		}
		pending = ""
	}
	body = strings.Join(lines, "\n")
	// a label nothing names is dropped with its line
	var out []string
	for _, l := range strings.Split(body, "\n") {
		if m := labelLineRe.FindStringSubmatch(strings.TrimLeft(l, "\t")); m != nil && m[1] != "default" {
			if !regexp.MustCompile(`\b(break|continue|goto) ` + m[1] + `\b`).MatchString(body) {
				continue
			}
		}
		out = append(out, l)
	}
	return strings.Join(out, "\n")
}

var (
	labelLineRe  = regexp.MustCompile(`^(\w+):$`)
	branchLineRe = regexp.MustCompile(`^(break|continue) (\w+)$`)
)

var ifOpenRe = regexp.MustCompile(`^(\t*)if (.*) \{$`)

// deadSets finds stores whose value is never read. A function the
// analysis cannot follow keeps all its stores.
func deadSets(body []*wat.Sexpr) (dead map[*wat.Sexpr]bool) {
	defer func() {
		if recover() != nil {
			dead = nil
		}
	}()
	return wat.DeadSets(body)
}

// readsVar reports whether a body uses a variable other than as the target
// of an assignment.
// declareAtFirstUse declares with := each variable whose first mention
// is an assignment in the function's own block, when the assigned value
// has the variable's type; an untyped constant would not.
func (g *fgen) declareAtFirstUse(body string, vars []Local, types map[string]string) string {
	for _, v := range vars {
		loc := regexp.MustCompile(`\b` + v.Name + `\b`).FindStringIndex(body)
		if loc == nil {
			continue
		}
		start := strings.LastIndexByte(body[:loc[0]], '\n') + 1
		end := strings.IndexByte(body[loc[0]:], '\n')
		if end < 0 {
			continue
		}
		line := body[start : loc[0]+end]
		value, ok := strings.CutPrefix(line, "\t"+v.Name+" = ")
		if !ok || regexp.MustCompile(`\b`+v.Name+`\b`).MatchString(value) {
			continue
		}
		e, err := parseExpr(value)
		if err != nil || g.typeOf(e, types) != types[v.Name] {
			continue
		}
		body = body[:start] + "\t" + v.Name + " := " + value + body[loc[0]+end:]
	}
	return body
}

// hoistSelects takes each rt.Sel32 or rt.Sel64 out of the expression it
// sits in, as Go has no conditional expression: return Sel(c, a, b)
// becomes if c { return a }; return b, and a choice inside another
// statement is assigned to a variable before it, named after the parameter
// it is passed to. Expressions call nothing with side effects, so the
// choice may be made before the rest of the statement.
func (g *fgen) hoistSelects(body string, types map[string]string) string {
	taken := map[string]bool{}
	for _, w := range identRe.FindAllString(body, -1) {
		taken[w] = true
	}
	lines := strings.Split(body, "\n")
	for i := 0; i < len(lines); i++ {
		l := lines[i]
		t := strings.TrimLeft(l, "\t")
		indent := l[:len(l)-len(t)]
		at := selCallRe.FindStringIndex(t)
		if at == nil || strings.HasPrefix(t, "case ") || strings.HasPrefix(t, "for ") {
			continue
		}
		end := matchParen(t, at[1]-1)
		if end < 0 {
			continue
		}
		// a choice in an else-if condition is made before the chain, when it
		// reads only locals, which the conditions before it cannot change
		insertAt := i
		if strings.HasPrefix(t, "} else if ") {
			if strings.Contains(t[at[0]:end+1], "m.") {
				continue
			}
			for insertAt--; insertAt >= 0 && !strings.HasPrefix(lines[insertAt], indent+"if "); insertAt-- {
				if lines[insertAt] != "" && !strings.HasPrefix(lines[insertAt], indent+"\t") && !strings.HasPrefix(lines[insertAt], indent+"} else") {
					insertAt = -1
					break
				}
			}
			if insertAt < 0 {
				continue
			}
		}
		sel, err := parseExpr(t[at[0] : end+1])
		if err != nil || !isSelect(sel) {
			continue
		}
		c, a, b := sel.args[0], sel.args[1], sel.args[2]
		var out []string
		if t == "return "+t[at[0]:end+1] {
			out = []string{indent + "if " + c.print() + " {", indent + "\treturn " + a.print(), indent + "}", indent + "return " + b.print()}
		} else {
			typ := "uint32"
			if sel.fn == "rt.Sel64" {
				typ = "uint64"
			}
			name := g.choiceName(t, at[0], taken)
			if bt := g.typeOf(b, types); bt == typ && !isSelect(b) {
				out = []string{indent + name + " := " + b.print(), indent + "if " + c.print() + " {", indent + "\t" + name + " = " + a.print(), indent + "}"}
			} else {
				out = append([]string{indent + "var " + name + " " + typ}, strings.Split(indent+selectStmt(indent, name, "", sel)+"\n"+indent+"}", "\n")...)
			}
			if insertAt != i {
				lines[i] = indent + t[:at[0]] + name + t[end+1:]
				lines = append(lines[:insertAt], append(out, lines[insertAt:]...)...)
				i = insertAt - 1 // the new lines may hold further choices
				continue
			}
			out = append(out, indent+t[:at[0]]+name+t[end+1:])
		}
		lines = append(lines[:i], append(out, lines[i+1:]...)...)
		i-- // the new lines may hold further choices
	}
	return strings.Join(lines, "\n")
}

var selCallRe = regexp.MustCompile(`\brt\.Sel(32|64)\(`)

// matchParen returns the index of the parenthesis closing the one at open,
// or -1.
func matchParen(s string, open int) int {
	depth := 0
	for i := open; i < len(s); i++ {
		switch s[i] {
		case '\'':
			// a rune literal may hold a parenthesis
			if j := strings.IndexByte(s[i+1:], '\''); j >= 0 && s[i+1] != '\'' {
				if s[i+1] == '\\' {
					j = strings.IndexByte(s[i+3:], '\'') + 2
				}
				i += j + 1
			}
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	return -1
}

// choiceName names the variable holding a choice found at pos in a
// statement: the parameter it is passed to, or "choice".
func (g *fgen) choiceName(stmt string, pos int, taken map[string]bool) string {
	name := "choice"
	// find the call whose argument list the choice starts
	depth := 0
	for i := pos - 1; i >= 0; i-- {
		switch stmt[i] {
		case ')':
			depth++
		case '(':
			if depth > 0 {
				depth--
				continue
			}
			if m := regexp.MustCompile(`m\.(\w+)$`).FindStringSubmatch(stmt[:i]); m != nil {
				if f := g.mod.funcByGoName(m[1]); f != nil {
					k := strings.Count(argsDepth0(stmt[i+1:pos]), ",")
					if k < len(f.Params) && f.Params[k].Name != "" {
						name = camel(f.Params[k].Name[1:])
					}
				}
			}
			i = 0
		}
	}
	if alt, ok := localAlternatives[name]; ok {
		name = alt
	}
	if goReserved[name] {
		name += "Choice"
	}
	for base, n := name, 2; taken[name]; n++ {
		name = fmt.Sprintf("%s%d", base, n)
	}
	taken[name] = true
	return name
}

// argsDepth0 keeps the text of an argument list outside nested
// parentheses, so its commas separate the arguments.
func argsDepth0(s string) string {
	var sb strings.Builder
	depth := 0
	for _, r := range s {
		switch r {
		case '(':
			depth++
		case ')':
			depth--
		default:
			if depth == 0 {
				sb.WriteRune(r)
			}
		}
	}
	return sb.String()
}

// typeOf infers the Go type of a generated expression, or "" for an
// untyped constant or a type it cannot tell.
func (g *fgen) typeOf(e *expr, types map[string]string) string {
	switch {
	case e.index:
		if e.fn == "m.Mem" {
			return "byte"
		}
		return ""
	case e.leaf != "":
		if t, ok := types[e.leaf]; ok {
			return t
		}
		if field, ok := strings.CutPrefix(e.leaf, "m."); ok {
			for _, gl := range g.mod.Globals {
				if gl.GoName == field && gl.Mutable {
					if g.flags[gl] {
						return "bool"
					}
					return gl.Type.goType()
				}
			}
		}
		if e.leaf == "true" || e.leaf == "false" {
			return "bool"
		}
		return ""
	case e.fn != "":
		switch e.fn {
		case "uint32", "uint64", "int32", "int64", "byte", "bool":
			return e.fn
		}
		if name, ok := strings.CutPrefix(e.fn, "m."); ok {
			if f := g.mod.funcByGoName(name); f != nil && len(f.Results) == 1 {
				if g.boolFuncs[name] {
					return "bool"
				}
				return f.Results[0].goType()
			}
			return ""
		}
		switch e.fn {
		case "binary.LittleEndian.Uint32":
			return "uint32"
		case "binary.LittleEndian.Uint64":
			return "uint64"
		}
		if name, ok := strings.CutPrefix(e.fn, "rt."); ok {
			switch {
			case strings.HasPrefix(name, "LdV") || strings.HasSuffix(name, "V"):
				return ""
			case strings.Contains(name, "64"):
				return "uint64"
			case strings.HasPrefix(name, "Ld") || strings.HasPrefix(name, "Sel") || name == "B2u":
				return "uint32"
			}
		}
		return ""
	case e.op == "!":
		return "bool"
	case e.op == "u^":
		return g.typeOf(e.args[0], types)
	}
	switch e.op {
	case "==", "!=", "<", "<=", ">", ">=", "&&", "||":
		return "bool"
	case "<<", ">>":
		return g.typeOf(e.args[0], types)
	}
	if t := g.typeOf(e.args[0], types); t != "" {
		return t
	}
	return g.typeOf(e.args[1], types)
}

// dropUnreadTemps removes the assignments to temporaries that nothing
// reads, which folding a constant condition leaves behind; a call to a
// function with side effects keeps its statement.
func dropUnreadTemps(body string, temps []Local, pure map[string]bool) string {
	for _, t := range temps {
		if !strings.Contains(body, t.Name) || readsVar(body, t.Name) {
			continue
		}
		re := regexp.MustCompile(`(?m)^(\t*)` + t.Name + ` = (.*)\n`)
		body = re.ReplaceAllStringFunc(body, func(line string) string {
			m := re.FindStringSubmatch(line)
			if c := topCallRe.FindStringSubmatch(m[2]); c != nil && !pure[c[1]] {
				return m[1] + m[2] + "\n"
			}
			return ""
		})
	}
	return body
}

// nameTemps renames each temporary after what it holds or where it goes:
// the function whose result it holds, or the parameter it is passed to.
func (g *fgen) nameTemps(body string, params []string, locals []Local) string {
	taken := map[string]bool{"m": true}
	for _, p := range params {
		taken[strings.Fields(p)[0]] = true
	}
	for _, l := range locals {
		taken[l.Name] = true
	}
	for _, w := range identRe.FindAllString(body, -1) {
		taken[w] = true
	}
	body = g.foldCopies(body, locals)
	for i, t := range g.temps {
		if !strings.Contains(body, t.Name) {
			continue
		}
		name := g.tempHint[t.Name]
		if name == "" {
			name = g.tempName(body, t.Name)
		}
		if name == "" || goReserved[name] || tempName.MatchString(name) {
			continue
		}
		if alt, ok := localAlternatives[name]; ok {
			name = alt
		}
		for base, n := name, 2; taken[name]; n++ {
			name = fmt.Sprintf("%s%d", base, n)
		}
		taken[name] = true
		body = regexp.MustCompile(`\b`+t.Name+`\b`).ReplaceAllString(body, name)
		g.temps[i].Name = name
	}
	return body
}

// foldCopies gives a temporary whose only read copies it into a local the
// local's name, when nothing else touches the local from the temporary's
// first assignment to the copy, and drops the copy.
func (g *fgen) foldCopies(body string, locals []Local) string {
	typeOf := map[string]ValType{}
	for _, l := range slices.Concat(locals, g.temps) {
		typeOf[l.Name] = l.Type
	}
	var kept []Local
	for _, t := range g.temps {
		word := regexp.MustCompile(`\b` + t.Name + `\b`)
		lines := strings.Split(body, "\n")
		first, copyAt, target := -1, -1, ""
		ok := true
		for i, l := range lines {
			tr := strings.TrimLeft(l, "\t")
			if !word.MatchString(tr) {
				continue
			}
			if strings.HasPrefix(tr, t.Name+" = ") && !word.MatchString(strings.TrimPrefix(tr, t.Name+" = ")) {
				if first < 0 {
					first = i
				}
				continue
			}
			if m := copyRe.FindStringSubmatch(tr); m != nil && m[2] == t.Name && copyAt < 0 {
				copyAt, target = i, m[1]
				continue
			}
			ok = false
		}
		if !ok || first < 0 || copyAt < first || typeOf[target] != t.Type {
			kept = append(kept, t)
			continue
		}
		touched := regexp.MustCompile(`\b` + target + `\b`)
		for _, l := range lines[first:copyAt] {
			if touched.MatchString(l) {
				ok = false
			}
		}
		if !ok {
			kept = append(kept, t)
			continue
		}
		for i := first; i < copyAt; i++ {
			lines[i] = word.ReplaceAllString(lines[i], target)
		}
		body = strings.Join(append(lines[:copyAt], lines[copyAt+1:]...), "\n")
	}
	if len(kept) < len(g.temps) {
		g.temps = kept
		// a fold can leave another copy foldable
		return g.foldCopies(body, locals)
	}
	return body
}

var copyRe = regexp.MustCompile(`^(\w+) = (t\d+)$`)

// tempName names a temporary after what it holds or where it goes: the
// function whose result it holds, the parameter it is passed to, or its
// role.
func (g *fgen) tempName(body, temp string) string {
	if m := regexp.MustCompile(`(?m)^\t*` + temp + ` = (?:rt\.B2u\()?m\.(\w+)\(`).FindStringSubmatch(body); m != nil {
		return lowerFirst(m[1])
	}
	if f, k := g.argOf(body, temp); f != nil && f.Params[k].Name != "" {
		return camel(f.Params[k].Name[1:])
	}
	if regexp.MustCompile(`(?m)^\t*` + temp + ` = rt\.Grow\(`).MatchString(body) {
		return "oldPages"
	}
	return roleName(body, temp)
}

// roleName names a temporary by how it is read: "result" when only
// returned, "cond" when only tested by an if.
func roleName(body, temp string) string {
	word := regexp.MustCompile(`\b` + temp + `\b`)
	role := ""
	for _, l := range strings.Split(body, "\n") {
		t := strings.TrimLeft(l, "\t")
		if !word.MatchString(t) || strings.HasPrefix(t, temp+" = ") || strings.HasPrefix(t, temp+" := ") {
			continue
		}
		r := ""
		switch {
		case t == "return "+temp:
			r = "result"
		case strings.HasPrefix(t, "if ") || strings.HasPrefix(t, "} else if "):
			r = "cond"
		default:
			return ""
		}
		if role != "" && role != r {
			return ""
		}
		role = r
	}
	return role
}

var identRe = regexp.MustCompile(`\b[A-Za-z_]\w*\b`)

// argOf finds a call that takes temp as a whole argument and returns the
// callee and the argument's position.
func (g *fgen) argOf(body, temp string) (*Func, int) {
	re := regexp.MustCompile(`m\.(\w+)\(([^()]*\b` + temp + `\b[^()]*)\)`)
	for _, m := range re.FindAllStringSubmatch(body, -1) {
		f := g.mod.funcByGoName(m[1])
		if f == nil {
			continue
		}
		for k, a := range strings.Split(m[2], ", ") {
			if a == temp && k < len(f.Params) {
				return f, k
			}
		}
	}
	return nil, 0
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// topCallRe matches a statement that is one method call.
var topCallRe = regexp.MustCompile(`^m\.(\w+)\(.*\)$`)

// mayGrow reports whether a function body can grow memory: itself, or
// through a call to a function that can.
func (g *fgen) mayGrow(body string) bool {
	if strings.Contains(body, "rt.Grow") {
		return true
	}
	for _, m := range calleeRe.FindAllStringSubmatch(body, -1) {
		if g.growers[m[1]] {
			return true
		}
	}
	return false
}

var calleeRe = regexp.MustCompile(`\bm\.(\w+)\(`)

// growers returns the Go names of the functions that can grow memory:
// those with memory.grow, imports, which the host implements, and their
// callers. An indirect call can reach any function, so it counts as one.
func growers(mod *Module) map[string]bool {
	grows := map[*Func]bool{}
	for _, f := range mod.Funcs {
		if f.Import != nil {
			grows[f] = true
		}
	}
	var reaches func(n *wat.Sexpr) bool
	reaches = func(n *wat.Sexpr) bool {
		if !n.IsList {
			return false
		}
		switch head := n.Head(); {
		case head == "memory.grow", head == "call_indirect":
			return true
		case head == "call" && len(n.List) > 1:
			if f := mod.FuncByRef[n.List[1].Atom]; f == nil || grows[f] {
				return true
			}
		}
		for _, c := range n.List[1:] {
			if reaches(c) {
				return true
			}
		}
		return false
	}
	for changed := true; changed; {
		changed = false
		for _, f := range mod.Funcs {
			if grows[f] {
				continue
			}
			for _, n := range f.Body {
				if reaches(n) {
					grows[f] = true
					changed = true
					break
				}
			}
		}
	}
	names := map[string]bool{}
	for f := range grows {
		names[f.GoName] = true
	}
	return names
}

// pureFuncs returns the Go names of the functions that neither write
// memory or globals nor call a function that does. A trap is not counted
// as a side effect, as loads are not.
func pureFuncs(mod *Module) map[string]bool {
	impure := map[*Func]bool{}
	for _, f := range mod.Funcs {
		if f.Import != nil {
			impure[f] = true
		}
	}
	var effects func(n *wat.Sexpr) bool
	effects = func(n *wat.Sexpr) bool {
		if !n.IsList {
			return false
		}
		head := n.Head()
		switch {
		case head == "global.set", head == "call_indirect", head == "unreachable",
			strings.Contains(head, ".store"), strings.HasPrefix(head, "memory."):
			return true
		case head == "call" && len(n.List) > 1:
			if f := mod.FuncByRef[n.List[1].Atom]; f == nil || impure[f] {
				return true
			}
		}
		for _, c := range n.List[1:] {
			if effects(c) {
				return true
			}
		}
		return false
	}
	for changed := true; changed; {
		changed = false
		for _, f := range mod.Funcs {
			if impure[f] {
				continue
			}
			for _, n := range f.Body {
				if effects(n) {
					impure[f] = true
					changed = true
					break
				}
			}
		}
	}
	pure := map[string]bool{}
	for _, f := range mod.Funcs {
		if !impure[f] {
			pure[f.GoName] = true
		}
	}
	return pure
}

func readsVar(body, name string) bool {
	re := regexp.MustCompile(`\b` + name + `\b( =[^=])?`)
	for _, m := range re.FindAllStringSubmatchIndex(body, -1) {
		if m[2] < 0 {
			return true
		}
		// an assignment target starts its line
		start := strings.LastIndexByte(body[:m[0]], '\n') + 1
		if strings.TrimSpace(body[start:m[0]]) != "" {
			return true
		}
	}
	return false
}

// endsTerminating reports whether the last top-level statement of a body
// ends the function.
func endsTerminating(body string) bool {
	lines := strings.Split(strings.TrimRight(body, "\n"), "\n")
	last := lines[len(lines)-1]
	if !strings.HasPrefix(last, "\t") || strings.HasPrefix(last, "\t\t") {
		return false
	}
	last = strings.TrimSpace(last)
	return strings.HasPrefix(last, "return") || strings.HasPrefix(last, "panic(") || strings.HasPrefix(last, "goto ")
}

func (g *fgen) push(v value) { g.stack = append(g.stack, v) }

func (g *fgen) pop() value {
	if len(g.stack) == 0 {
		failf("%s: operand stack underflow", g.fn.GoName)
	}
	v := g.stack[len(g.stack)-1]
	g.stack = g.stack[:len(g.stack)-1]
	return v
}

// numeric returns v as a numeric value.
func (g *fgen) numeric(v value) value {
	if v.isBool {
		return value{expr: g.asValue(v), typ: v.typ, stable: v.stable}
	}
	return v
}

// asValue renders v as a numeric expression.
func (g *fgen) asValue(v value) string {
	if v.isBool && v.isConst {
		return constLiteral(v.typ, v.c)
	}
	if v.isBool {
		if v.typ == I64 {
			return "rt.B2u64(" + trimParens(v.expr) + ")"
		}
		return "rt.B2u(" + trimParens(v.expr) + ")"
	}
	return v.expr
}

// asBool renders v as a Go condition.
func (g *fgen) asBool(v value) string {
	if v.isBool {
		return v.expr
	}
	if v.cond != "" {
		return v.cond
	}
	if v.byteExpr != "" {
		return "(" + v.byteExpr + " != 0)"
	}
	if v.isConst {
		return strconv.FormatBool(v.c != 0)
	}
	return "(" + v.expr + " != 0)"
}

// named binds a value written twice to a temporary with a name, unless it
// is a constant or a plain name already.
func (g *fgen) named(v value, name string) value {
	if v.isConst || identOnlyRe.MatchString(v.expr) {
		return v
	}
	t := g.newTemp(v.typ)
	g.line("%s = %s", t, trimParens(g.asValue(v)))
	if g.tempHint == nil {
		g.tempHint = map[string]string{}
	}
	g.tempHint[t] = name
	return value{expr: t, typ: v.typ, stable: true}
}

var identOnlyRe = regexp.MustCompile(`^[A-Za-z_][\w.]*$`)

// memRange writes the memory slice of n bytes from at.
func (g *fgen) memRange(at, n value) string {
	a := trimParens(g.asValue(at))
	end := tidyExpr("(" + a + ") + (" + trimParens(g.asValue(n)) + ")")
	if at.isConst && n.isConst {
		end = strconv.FormatUint(at.c+n.c, 10)
	}
	return "m.Mem[" + a + ":" + end + "]"
}

// readsState reports an operand that reads memory, globals or calls a
// method, which a call, a store or a global write may change.
func readsState(v value) bool { return strings.Contains(v.expr, "m.") }

// mentions reports operands that read the local name.
func mentions(name string) func(value) bool {
	re := regexp.MustCompile(`\b` + regexp.QuoteMeta(name) + `\b`)
	return func(v value) bool { return re.MatchString(v.expr) }
}

// spill evaluates pending operands into temporaries before a side effect.
func (g *fgen) spill() { g.spillIf(func(value) bool { return true }) }

// spillIf evaluates into temporaries the pending operands a write could
// change: those that read machine state, for a call or a store, or those
// that name a local, for an assignment to it.
func (g *fgen) spillIf(changes func(value) bool) {
	for i, v := range g.stack {
		if v.stable || v.isConst || !changes(v) {
			continue
		}
		var t string
		if v.isBool {
			t = g.newBoolTemp()
		} else {
			t = g.newTemp(v.typ)
		}
		g.line("%s = %s", t, trimParens(v.expr))
		g.stack[i] = value{expr: t, typ: v.typ, isBool: v.isBool, flag: v.flag, stable: true}
	}
}

func (g *fgen) genSeq(nodes []*wat.Sexpr) {
	for i, n := range nodes {
		if g.unreachable {
			return
		}
		g.noteInline(n, nodes[i+1:])
		g.childCont = g.contOf(nodes[i+1:])
		g.genInstr(n)
	}
}

// noteInline offers the code after a block to the block: when it is at
// most three simple statements and a branch, branches to the block can
// run it in place instead of jumping.
func (g *fgen) noteInline(n *wat.Sexpr, rest []*wat.Sexpr) {
	g.pendingInline = nil
	if !n.IsList || n.Head() != "block" {
		return
	}
	// a block that only a branch leaves, with one branch to it: the code
	// after it moves to that branch, whatever its size
	if body := blockBody(n); len(body) > 0 && endsInJump(body[len(body)-1]) && countBranches(body, n.List[1].Atom) == 1 {
		for k, r := range rest {
			if isJump(r) {
				g.pendingInline = rest[:k+1]
				return
			}
			if !inlinable(r) {
				break
			}
		}
		if c := g.contOf(rest); c != nil {
			g.pendingInline = c
			return
		}
	}
	size := 0
	for k, r := range rest {
		if isJump(r) {
			g.pendingInline = rest[:k+1]
			return
		}
		// longer tails, with control flow of their own, still inline while
		// they stay small
		if size += nodeCount(r); size > inlineBudget || !inlinable(r) {
			return
		}
	}
	// a tail that reaches the end of its sequence leaves it as the
	// sequence's end does
	if n := len(g.ends); n > 0 && g.ends[n-1] != nil && g.structuredEnd(g.ends[n-1]) {
		g.pendingInline = append(slices.Clone(rest), g.ends[n-1])
		return
	}
	// otherwise the code that runs after this sequence, while small
	if n := len(g.conts); n > 0 && g.conts[n-1] != nil {
		cont := g.conts[n-1]
		for _, c := range cont {
			if size += nodeCount(c); size > inlineBudget {
				return
			}
		}
		g.pendingInline = append(slices.Clone(rest), cont...)
	}
}

// contOf returns the code that runs after the statement before rest, up
// to its first jump, given the continuation of the enclosing sequence.
func (g *fgen) contOf(rest []*wat.Sexpr) []*wat.Sexpr {
	for k, r := range rest {
		if !inlinable(r) {
			return nil
		}
		if isJump(r) {
			return rest[:k+1]
		}
	}
	if n := len(g.conts); n > 0 && g.conts[n-1] != nil {
		return append(slices.Clone(rest), g.conts[n-1]...)
	}
	return nil
}

// structuredEnd reports whether writing a sequence end needs no goto.
func (g *fgen) structuredEnd(end *wat.Sexpr) bool {
	if end.Head() == "@exit" {
		return true
	}
	l, _ := g.findLabel(end.List[1].Atom)
	return l.isFunc || l.isLoop || l.breakStmt != "" || l.breaks != nil || l.inline != nil
}

// withEnd writes a sequence whose end amounts to the branch end and is
// followed by cont.
func (g *fgen) withEnd(end *wat.Sexpr, cont []*wat.Sexpr, write func()) {
	g.ends = append(g.ends, end)
	g.conts = append(g.conts, cont)
	write()
	g.ends = g.ends[:len(g.ends)-1]
	g.conts = g.conts[:len(g.conts)-1]
}

func brTo(label string) *wat.Sexpr { return list(atom("br"), atom(label)) }

// blockBody returns the statements of a named block without a result.
func blockBody(n *wat.Sexpr) []*wat.Sexpr {
	if len(n.List) < 3 || n.List[1].IsList || !strings.HasPrefix(n.List[1].Atom, "$") {
		return nil
	}
	body := n.List[2:]
	if len(body) > 0 && body[0].IsList && (body[0].Head() == "result" || body[0].Head() == "type") {
		return nil
	}
	return body
}

// endsInJump reports a statement after which control never falls through.
func endsInJump(n *wat.Sexpr) bool {
	switch n.Head() {
	case "br", "return", "unreachable", "br_table":
		return true
	}
	return false
}

// countBranches counts the branches to label in nodes, not counting
// those that an inner block of the same name captures.
func countBranches(nodes []*wat.Sexpr, label string) int {
	count := 0
	var walk func(n *wat.Sexpr)
	walk = func(n *wat.Sexpr) {
		if !n.IsList {
			return
		}
		switch n.Head() {
		case "block", "loop", "if":
			if len(n.List) > 1 && !n.List[1].IsList && n.List[1].Atom == label {
				return
			}
		case "br", "br_if", "br_table":
			for _, a := range n.List[1:] {
				if !a.IsList && a.Atom == label {
					count++
				}
			}
		}
		for _, c := range n.List[1:] {
			walk(c)
		}
	}
	for _, n := range nodes {
		walk(n)
	}
	return count
}

// inlineBudget bounds the WAT nodes a duplicated tail may hold.
const inlineBudget = 160

func nodeCount(n *wat.Sexpr) int {
	c := 1
	for _, x := range n.List {
		c += nodeCount(x)
	}
	return c
}

// inlinable reports a statement that can run in another place: no
// unreachable or indirect call, whose meaning a copy would not change.
func inlinable(n *wat.Sexpr) bool {
	if !n.IsList {
		return true
	}
	if n.Head() == "unreachable" || n.Head() == "call_indirect" {
		return false
	}
	for _, c := range n.List[1:] {
		if !inlinable(c) {
			return false
		}
	}
	return true
}

// freeLabels lists the labels a tail branches to that it does not define.
func freeLabels(nodes []*wat.Sexpr) []string {
	var out []string
	var walk func(n *wat.Sexpr, defined map[string]bool)
	walk = func(n *wat.Sexpr, defined map[string]bool) {
		if !n.IsList {
			return
		}
		switch n.Head() {
		case "block", "loop", "if":
			if len(n.List) > 1 && !n.List[1].IsList && strings.HasPrefix(n.List[1].Atom, "$") {
				inner := maps.Clone(defined)
				inner[n.List[1].Atom] = true
				defined = inner
			}
		case "br", "br_if", "br_table", "@exit":
			for _, a := range n.List[1:] {
				if !a.IsList && !defined[a.Atom] {
					out = append(out, a.Atom)
				}
			}
		}
		for _, c := range n.List[1:] {
			walk(c, defined)
		}
	}
	for _, n := range nodes {
		walk(n, map[string]bool{})
	}
	return out
}

// isJump reports an unconditional branch without a value, or a return.
func isJump(n *wat.Sexpr) bool {
	if !n.IsList {
		return false
	}
	switch n.Head() {
	case "br":
		return len(n.List) == 2 && !n.List[1].IsList
	case "return":
		return isSimple(n)
	}
	return false
}

// isSimple reports an instruction without control flow.
func isSimple(n *wat.Sexpr) bool {
	if !n.IsList {
		return true
	}
	switch n.Head() {
	case "block", "loop", "if", "br", "br_if", "br_table", "unreachable", "call_indirect":
		return false
	}
	for _, c := range n.List[1:] {
		if !isSimple(c) {
			return false
		}
	}
	return true
}

func constValue(t ValType, c uint64) value {
	if t == I32 {
		c &= 0xffffffff
	}
	return value{expr: constLiteral(t, c), typ: t, isConst: true, c: c, stable: true}
}

func boolConst(b bool) value {
	return value{expr: strconv.FormatBool(b), typ: I32, isBool: true, isConst: true, c: b2u(b), stable: true}
}

func b2u(b bool) uint64 {
	if b {
		return 1
	}
	return 0
}

func (g *fgen) findLabel(ref string) (*label, int) {
	if ref == "" {
		failf("missing branch label")
	}
	if ref[0] >= '0' && ref[0] <= '9' {
		d, _ := strconv.Atoi(ref)
		i := len(g.labels) - 1 - d
		if i < 0 {
			failf("branch depth %d out of range", d)
		}
		return g.labels[i], i
	}
	for i := len(g.labels) - 1; i >= 0; i-- {
		if !g.labels[i].isFunc && g.labels[i].watName == ref {
			return g.labels[i], i
		}
	}
	failf("%s: unknown label %s", g.fn.GoName, ref)
	return nil, 0
}

// jump returns the statements of a branch to l, with its value if it takes
// one.
func (g *fgen) jump(l *label, v *value) []string {
	switch {
	case l.isFunc:
		if l.result != "" {
			return []string{"return " + g.returned(*v)}
		}
		return []string{"return"}
	case l.isLoop:
		l.used = true
		return []string{"continue " + l.goName}
	case l.breakStmt != "":
		l.used = true
		return []string{l.breakStmt}
	case l.breaks != nil:
		l.breaks.used = true
		l.breaks.broken = true
		l.used = true
		return []string{"break " + l.breaks.goName}
	}
	l.used = true
	l.jumped = true
	var out []string
	if l.result != "" {
		out = append(out, l.resTemp+" = "+trimParens(g.asValue(*v)))
	}
	return append(out, "goto "+l.goName)
}

// emitJump writes a branch to l: the block's short tail in place when its
// branch targets resolve to the same labels here, or a jump statement.
func (g *fgen) emitJump(l *label, v *value) {
	if l.inline != nil && l.breaks == nil && l.breakStmt == "" && v == nil && g.inlineDepth < 4 && g.sameTargets(l) {
		base := len(g.stack)
		g.inlineDepth++
		g.genSeq(l.inline)
		g.inlineDepth--
		g.stack = g.stack[:base]
		g.unreachable = true
		return
	}
	for _, st := range g.jump(l, v) {
		g.line("%s", st)
	}
}

func (g *fgen) sameTargets(l *label) bool {
	for k, ref := range freeLabels(l.inline) {
		if t, _ := g.findLabel(ref); t != l.targets[k] {
			return false
		}
	}
	return true
}

// takesValue reports whether a branch to l carries a value.
func takesValue(l *label) bool { return l.result != "" && !l.isLoop }

func splitInstr(n *wat.Sexpr) (head string, imms []string, operands []*wat.Sexpr) {
	head = n.Head()
	for _, part := range n.List[1:] {
		if part.IsList {
			operands = append(operands, part)
		} else {
			imms = append(imms, part.Atom)
		}
	}
	return
}

func (g *fgen) genInstr(n *wat.Sexpr) {
	if !n.IsList {
		failf("%s: unfolded instruction %q is unsupported", g.fn.GoName, n.Atom)
	}
	head := n.Head()
	switch head {
	case "block", "loop":
		g.genBlock(n, head == "loop", nil)
		return
	case "if":
		g.genIf(n, nil, nil)
		return
	case "call_indirect":
		g.genCallIndirect(n)
		return
	case "@exit":
		// leaving a loop at the end of its body
		l, _ := g.findLabel(n.List[1].Atom)
		l.used, l.broken = true, true
		g.line("break %s", l.goName)
		g.unreachable = true
		return
	}
	_, imms, operands := splitInstr(n)
	for _, op := range operands {
		g.genInstr(op)
		if g.unreachable {
			return
		}
	}
	if g.dead[n] {
		// the operand is pure: calls already sit in their own statements
		if head == "local.set" {
			g.pop()
			return
		}
		if head == "local.tee" {
			return
		}
	}
	g.apply(head, imms)
}

func (g *fgen) blockHeader(rest []*wat.Sexpr) (name string, result ValType, body []*wat.Sexpr) {
	if len(rest) > 0 && !rest[0].IsList && strings.HasPrefix(rest[0].Atom, "$") {
		name = rest[0].Atom
		rest = rest[1:]
	}
	for len(rest) > 0 && rest[0].IsList && (rest[0].Head() == "result" || rest[0].Head() == "type" || rest[0].Head() == "param") {
		switch rest[0].Head() {
		case "result":
			if len(rest[0].List) != 2 {
				failf("multi-value blocks are unsupported")
			}
			result = parseValType(rest[0].List[1].Atom)
		default:
			failf("block types other than a single result are unsupported")
		}
		rest = rest[1:]
	}
	return name, result, rest
}

func (g *fgen) newLabel(watName string, isLoop bool, result ValType) *label {
	g.nlabel++
	name := fmt.Sprintf("block%d", g.nlabel)
	if isLoop {
		name = fmt.Sprintf("loop%d", g.nlabel)
	}
	if watName != "" && !strings.HasPrefix(watName, "$__") {
		if c := camel(watName[1:]); c != "" && !goReserved[c] {
			name = c
		}
	}
	if g.labelNames == nil {
		g.labelNames = map[string]bool{}
	}
	for base, n := name, 2; g.labelNames[name]; n++ {
		name = fmt.Sprintf("%s%d", base, n)
	}
	g.labelNames[name] = true
	l := &label{goName: name, watName: watName, isLoop: isLoop, result: result}
	if result != "" && !isLoop {
		l.resTemp = g.newTemp(result)
	}
	return l
}

// genBlock writes a block or loop. tail lists outer blocks that end where
// this one does.
func (g *fgen) genBlock(n *wat.Sexpr, isLoop bool, tail []*label) {
	cont := g.childCont
	name, result, body := g.blockHeader(n.List[1:])
	g.spill()
	if isLoop {
		g.genLoop(name, result, body)
		return
	}
	if result == "" && byteSwitchRe.MatchString(name) && g.genByteSwitch(name, body) {
		return
	}
	l := g.newLabel(name, false, result)
	if inline := g.pendingInline; inline != nil && result == "" {
		l.inline = inline
		for _, ref := range freeLabels(inline) {
			t, _ := g.findLabel(ref)
			l.targets = append(l.targets, t)
		}
	}
	g.pendingInline = nil
	// a block that ends with a loop ends where the loop does: inside the
	// loop, a branch to the block breaks out of it
	if n := len(body); result == "" && n > 0 && body[n-1].IsList && body[n-1].Head() == "loop" {
		loopName, loopResult, loopBody := g.blockHeader(body[n-1].List[1:])
		if loopResult == "" {
			g.labels = append(g.labels, l)
			if n > 1 {
				g.withEnd(nil, nil, func() { g.genSeq(body[:n-1]) })
			}
			reachedLoop := !g.unreachable
			if reachedLoop {
				g.childCont = cont
				g.genLoop(loopName, "", loopBody, l)
			}
			g.labels = g.labels[:len(g.labels)-1]
			if l.jumped {
				// jumps from before the loop land after it
				g.depth--
				g.line("%s:", l.goName)
				g.depth++
				g.unreachable = false
			}
			return
		}
	}
	base := len(g.stack)
	g.labels = append(g.labels, l)
	if result == "" {
		g.withEnd(brTo(name), cont, func() { g.genSeqTail(body, append(slices.Clone(tail), l)) })
	} else {
		g.withEnd(nil, nil, func() { g.genSeq(body) })
	}
	g.labels = g.labels[:len(g.labels)-1]
	fallthroughReachable := !g.unreachable
	if fallthroughReachable && result != "" {
		v := g.pop()
		g.line("%s = %s", l.resTemp, trimParens(g.asValue(v)))
	}
	if fallthroughReachable && len(g.stack) != base {
		failf("%s: block leaves %d values", g.fn.GoName, len(g.stack)-base)
	}
	g.stack = g.stack[:base]
	if l.jumped {
		g.depth--
		g.line("%s:", l.goName)
		g.depth++
	}
	g.unreachable = !fallthroughReachable && !l.used
	if result != "" && !g.unreachable {
		g.push(value{expr: l.resTemp, typ: result, stable: true})
	}
}

// namesLoop reports whether the loop body written after head still
// branches to the loop by name.
func namesLoop(text, head, name string) bool {
	_, body, _ := strings.Cut(text, head)
	return strings.Contains(body, "continue "+name+"\n") || strings.Contains(body, "break "+name+"\n")
}

var doWhileRe = regexp.MustCompile(`\n(\t+)if (.*) \{\n\t+continue (\w+)\n\t+\}\n$`)

var byteSwitchRe = regexp.MustCompile(`^\$byteSwitch\d+_default$`)

// genByteSwitch writes the block ladder that the preprocessor expands a
// byte-switch into as a Go switch on the byte. It reports false for a
// block of another shape.
func (g *fgen) genByteSwitch(name string, body []*wat.Sexpr) bool {
	cont := g.childCont
	prefix := strings.TrimSuffix(name, "default")
	// peel the case blocks: each holds the next one, then its own body and
	// a branch to the default label
	var bodies [][]*wat.Sexpr
	var caseNames []string
	cur := body
	var table *wat.Sexpr
	for {
		if len(cur) == 0 || !cur[0].IsList {
			return false
		}
		first := cur[0]
		if first.Head() == "br_table" && len(cur) == 1 {
			table = first
			break
		}
		if first.Head() != "block" || len(first.List) < 2 || !strings.HasPrefix(first.List[1].Atom, prefix) {
			return false
		}
		rest := cur[1:]
		if n := len(rest); n == 0 || rest[n-1].Head() != "br" || rest[n-1].List[1].Atom != name {
			return false
		}
		bodies = append(bodies, rest[:len(rest)-1])
		caseNames = append(caseNames, first.List[1].Atom)
		cur = first.List[2:]
	}
	_, imms, operands := splitInstr(table)
	if len(operands) != 1 || operands[0].Head() != "i32.sub" {
		return false
	}
	sub := operands[0].List[1:]
	if len(sub) != 2 || sub[0].Head() != "local.get" || sub[1].Head() != "i32.const" {
		return false
	}
	scrutinee, _ := g.local(sub[0].List[1].Atom)
	lo := int(parseInt(sub[1].List[1].Atom))
	values := map[string][]int{}
	for i, target := range imms[:len(imms)-1] {
		values[target] = append(values[target], lo+i)
	}
	g.spill()
	l := g.newLabel("", false, "")
	l.goName = strings.TrimPrefix(strings.TrimSuffix(prefix, "_"), "$")
	l.watName = name
	l.breakStmt = "break " + l.goName
	head := fmt.Sprintf("@@switch%d@@", g.nlabel)
	g.line("%s", head)
	g.labels = append(g.labels, l)
	base := len(g.stack)
	// cases in source order: innermost block first
	for k := len(bodies) - 1; k >= 0; k-- {
		var keys []string
		for _, v := range values[caseNames[k]] {
			keys = append(keys, byteLiteral(v))
		}
		if len(keys) == 0 {
			continue
		}
		g.line("case %s:", strings.Join(keys, ", "))
		g.depth++
		g.withEnd(brTo(name), cont, func() { g.genSeqTail(bodies[k], []*label{l}) })
		g.stack = g.stack[:base]
		g.unreachable = false
		g.depth--
	}
	g.labels = g.labels[:len(g.labels)-1]
	g.line("}")
	opener := "switch " + scrutinee + " {"
	if l.used {
		opener = l.goName + ":\n" + strings.Repeat("\t", g.depth+1) + opener
	}
	text := strings.Replace(g.out.String(), head, opener, 1)
	g.out.Reset()
	g.out.WriteString(text)
	return true
}

var byteExprRe = regexp.MustCompile(`^(?:uint32\(m\.Mem\[.*\]\)|m\.[A-Za-z0-9]*Byte\(.*\)|(?:c|ch|b|q|c\d|quote|delim|close|open|next|prev|term|sep|first|last|lead)\d*_?)$`)

// isByteExpr guesses whether an expression holds a byte: a byte load, a
// call to a *Byte function, or a local named like one.
func isByteExpr(e string) bool { return byteExprRe.MatchString(e) }

// byteLiteral writes a byte as a rune literal when it is printable.
func byteLiteral(b int) string {
	switch {
	case b == '\'':
		return `'\''`
	case b == '\\':
		return `'\\'`
	case b == '\n':
		return `'\n'`
	case b == '\t':
		return `'\t'`
	case b == '\r':
		return `'\r'`
	case b >= 0x20 && b < 0x7f:
		return "'" + string(rune(b)) + "'"
	}
	return strconv.Itoa(b)
}

// genLoop writes a WAT loop as a Go for loop: a branch to the loop
// continues it, and reaching the end of the body breaks out. block is the
// block that ends with the loop, if any.
func (g *fgen) genLoop(name string, result ValType, body []*wat.Sexpr, blocks ...*label) {
	cont := g.childCont
	l := g.newLabel(name, true, result)
	var block *label
	if len(blocks) > 0 {
		block = blocks[len(blocks)-1]
	}
	for _, b := range blocks {
		b.breaks = l
	}
	defer func() {
		for _, b := range blocks {
			b.breaks = nil
		}
	}()
	var res string
	if result != "" {
		res = g.newTemp(result)
	}
	base := len(g.stack)
	head := fmt.Sprintf("@@loop%d@@", g.nlabel)
	g.line("%s", head)
	g.depth++
	g.labels = append(g.labels, l)
	exit := list(atom("@exit"), atom(name))
	if block != nil {
		exit = brTo(block.watName)
	}
	if result != "" {
		cont = nil
	}
	g.withEnd(exit, cont, func() { g.genSeq(body) })
	g.labels = g.labels[:len(g.labels)-1]
	fallthroughReachable := !g.unreachable
	// a continue at the end of the loop body is how a Go loop body ends
	// anyway
	if trailing := strings.Repeat("\t", g.depth+1) + "continue " + l.goName + "\n"; !fallthroughReachable && strings.HasSuffix(g.out.String(), trailing) {
		text := strings.TrimSuffix(g.out.String(), trailing)
		g.out.Reset()
		g.out.WriteString(text)
		l.used = namesLoop(text, head, l.goName)
	}
	// a loop that ends `if c { continue }` and leaves otherwise is a
	// do-while: it ends `if !c { break }`
	indent := strings.Repeat("\t", g.depth+1)
	if m := doWhileRe.FindStringSubmatch(g.out.String()); fallthroughReachable && result == "" && m != nil && m[1] == indent && m[3] == l.goName {
		text := strings.TrimSuffix(g.out.String(), m[0][1:])
		g.out.Reset()
		g.out.WriteString(text)
		g.line("if %s {", negate(m[2]))
		g.line("\tbreak")
		g.line("}")
		l.used = namesLoop(text, head, l.goName)
		l.broken = true
		fallthroughReachable = false
	}
	if fallthroughReachable {
		if result != "" {
			v := g.pop()
			g.line("%s = %s", res, trimParens(g.asValue(v)))
		}
		g.line("break")
	}
	if fallthroughReachable && len(g.stack) != base {
		failf("%s: loop leaves %d values", g.fn.GoName, len(g.stack)-base)
	}
	g.stack = g.stack[:base]
	g.depth--
	g.line("}")
	opener := "for {"
	if l.used {
		opener = l.goName + ":\n" + strings.Repeat("\t", g.depth+1) + "for {"
	}
	text := strings.Replace(g.out.String(), head, opener, 1)
	g.out.Reset()
	g.out.WriteString(text)
	g.unreachable = !fallthroughReachable && !l.broken
	if g.unreachable && g.depth == 0 {
		// a for loop without a break ends the function
		g.terminalEnd = g.out.Len()
	}
	if result != "" && !g.unreachable {
		g.push(value{expr: res, typ: result, stable: true})
	}
}

// genIf writes an if. In tail position, tail lists the blocks whose end is
// the end of the enclosing sequence, and rest holds the statements after
// the if. An arm that ends by branching to such a block needs no branch:
// the other arm takes rest instead. genIf reports whether it used rest.
func (g *fgen) genIf(n *wat.Sexpr, tail []*label, rest []*wat.Sexpr) bool {
	name, result, parts := g.blockHeader(n.List[1:])
	var thenSeq, elseSeq, cond []*wat.Sexpr
	hasElse := false
	seenThen := false
	for _, part := range parts {
		switch {
		case part.IsList && part.Head() == "then" && !seenThen:
			thenSeq = part.List[1:]
			seenThen = true
		case part.IsList && part.Head() == "else" && !hasElse:
			elseSeq = part.List[1:]
			hasElse = true
		default:
			cond = append(cond, part)
		}
	}
	cont := g.childCont
	parentCont := []*wat.Sexpr(nil)
	if n := len(g.conts); n > 0 {
		parentCont = g.conts[n-1]
	}
	g.withEnd(nil, nil, func() { g.genSeq(cond) })
	if g.unreachable {
		return false
	}
	c := g.pop()
	if c.isConst && result == "" {
		// a constant condition leaves only the arm it takes, as a block
		taken := thenSeq
		if c.c == 0 {
			taken = elseSeq
		}
		block := list(atom("block"))
		if name != "" {
			block.List = append(block.List, atom(name))
		}
		block.List = append(block.List, taken...)
		var blockTail []*label
		if len(rest) == 0 {
			blockTail = tail
		}
		g.genBlock(block, false, blockTail)
		return false
	}
	g.spill()
	l := g.newLabel(name, false, result)
	base := len(g.stack)
	g.labels = append(g.labels, l)
	defer func() { g.labels = g.labels[:len(g.labels)-1] }()

	if result == "" && len(tail) > 0 {
		thenJumps := g.endsWithBranch(thenSeq, tail)
		elseJumps := g.endsWithBranch(elseSeq, tail)
		if thenJumps || elseJumps {
			thenBody, elseBody := thenSeq, elseSeq
			if thenJumps {
				thenBody = thenSeq[:len(thenSeq)-1]
			} else {
				thenBody = append(slices.Clone(thenSeq), rest...)
			}
			if elseJumps {
				elseBody = elseSeq[:len(elseSeq)-1]
			} else {
				elseBody = append(slices.Clone(elseSeq), rest...)
			}
			armTail := append(slices.Clone(tail), l)
			// the arms now hold rest, so after them comes what follows the
			// whole sequence
			g.ifElse(c, thenBody, elseBody, armTail, base, parentCont)
			if l.jumped {
				g.line("%s:", l.goName)
			}
			g.unreachable = false
			return true
		}
	}
	var armTail []*label
	if result == "" && len(tail) > 0 && len(rest) == 0 {
		// the end of the if ends the sequence
		armTail = append(slices.Clone(tail), l)
	} else if result == "" {
		armTail = []*label{l}
	}
	g.line("if %s {", trimParens(g.asBool(c)))
	g.depth++
	reachable := false
	if result != "" {
		cont = nil
	}
	g.withEnd(brTo(name), cont, func() { g.genSeqTail(thenSeq, armTail) })
	if !g.unreachable {
		reachable = true
		if result != "" {
			v := g.pop()
			g.line("%s = %s", l.resTemp, trimParens(g.asValue(v)))
		}
	}
	g.stack = g.stack[:base]
	g.unreachable = false
	g.depth--
	if len(elseSeq) > 0 {
		g.line("} else {")
		g.depth++
		g.withEnd(brTo(name), cont, func() { g.genSeqTail(elseSeq, armTail) })
		if !g.unreachable {
			reachable = true
			if result != "" {
				v := g.pop()
				g.line("%s = %s", l.resTemp, trimParens(g.asValue(v)))
			}
		}
		g.stack = g.stack[:base]
		g.unreachable = false
		g.depth--
	} else {
		if result != "" {
			failf("%s: if with a result needs an else arm", g.fn.GoName)
		}
		reachable = true
	}
	g.line("}")
	if l.jumped {
		g.line("%s:", l.goName)
	}
	g.unreachable = !reachable && !l.used
	if result != "" && !g.unreachable {
		g.push(value{expr: l.resTemp, typ: result, stable: true})
	}
	return false
}

// ifElse writes `if c { then } else { else }`, negating c when only the
// else arm has statements.
func (g *fgen) ifElse(c value, thenBody, elseBody []*wat.Sexpr, tail []*label, base int, cont []*wat.Sexpr) {
	if len(thenBody) == 0 && len(elseBody) == 0 {
		return
	}
	if len(thenBody) == 0 {
		thenBody, elseBody = elseBody, nil
		g.line("if %s {", negate(g.asBool(c)))
	} else {
		g.line("if %s {", trimParens(g.asBool(c)))
	}
	g.depth++
	end := brTo(tail[len(tail)-1].watName)
	g.withEnd(end, cont, func() { g.genSeqTail(thenBody, tail) })
	g.stack = g.stack[:base]
	g.unreachable = false
	g.depth--
	if len(elseBody) > 0 {
		g.line("} else {")
		g.depth++
		g.withEnd(end, cont, func() { g.genSeqTail(elseBody, tail) })
		g.stack = g.stack[:base]
		g.unreachable = false
		g.depth--
	}
	g.line("}")
}

// branchTarget returns the label a br or br_if names.
func (g *fgen) branchTarget(n *wat.Sexpr) *label {
	if !n.IsList || (n.Head() != "br" && n.Head() != "br_if") || len(n.List) < 2 || n.List[1].IsList {
		return nil
	}
	l, _ := g.findLabel(n.List[1].Atom)
	return l
}

// endsWithBranch reports whether a sequence ends with a plain branch to
// one of the tail blocks.
func (g *fgen) endsWithBranch(seq []*wat.Sexpr, tail []*label) bool {
	if len(seq) == 0 {
		return false
	}
	last := seq[len(seq)-1]
	return last.Head() == "br" && len(last.List) == 2 && slices.Contains(tail, g.branchTarget(last))
}

// genSeqTail writes a sequence whose end is the end of the tail blocks, so
// branches to them need no jump.
func (g *fgen) genSeqTail(nodes []*wat.Sexpr, tail []*label) {
	for i, n := range nodes {
		if g.unreachable {
			return
		}
		rest := nodes[i+1:]
		g.noteInline(n, rest)
		g.childCont = g.contOf(rest)
		if len(tail) > 0 && n.IsList {
			switch n.Head() {
			case "br":
				if len(n.List) == 2 && slices.Contains(tail, g.branchTarget(n)) {
					return
				}
			case "br_if":
				if len(n.List) == 3 && slices.Contains(tail, g.branchTarget(n)) {
					g.genInstr(n.List[2])
					if g.unreachable {
						return
					}
					c := g.pop()
					if len(rest) == 0 {
						return
					}
					g.spill()
					base := len(g.stack)
					g.line("if %s {", negate(g.asBool(c)))
					g.depth++
					g.genSeqTail(rest, tail)
					g.stack = g.stack[:base]
					g.unreachable = false
					g.depth--
					g.line("}")
					return
				}
			case "if":
				if g.genIf(n, tail, rest) {
					return
				}
				continue
			case "block":
				if len(rest) == 0 {
					g.genBlock(n, false, tail)
					continue
				}
			case "loop":
				// a loop that ends the sequence ends the tail blocks too: a
				// branch to one of them breaks out of the loop
				if name, result, body := g.blockHeader(n.List[1:]); len(rest) == 0 && result == "" {
					var blocks []*label
					for _, t := range tail {
						if !t.isLoop && !t.isFunc && t.breaks == nil && t.breakStmt == "" && t.result == "" {
							blocks = append(blocks, t)
						}
					}
					if len(blocks) > 0 {
						g.spill()
						g.genLoop(name, "", body, blocks...)
						continue
					}
				}
			}
		}
		if n.IsList && n.Head() == "if" {
			g.genIf(n, nil, nil)
			continue
		}
		g.genInstr(n)
	}
}

// negate writes the negation of a condition, flipping a comparison.
func negate(cond string) string {
	e := trimParens(cond)
	if op, at := topLevelComparison(e); op != "" {
		flip := map[string]string{"==": "!=", "!=": "==", "<": ">=", ">=": "<", ">": "<=", "<=": ">"}[op]
		return e[:at] + flip + e[at+len(op):]
	}
	if strings.HasPrefix(e, "!") && trimParens(e[1:]) != e[1:] {
		return trimParens(e[1:])
	}
	if strings.HasPrefix(e, "!") && !strings.ContainsAny(e[1:], " ") {
		return e[1:]
	}
	return "!(" + e + ")"
}

// topLevelComparison finds the single comparison operator outside
// parentheses in an expression without top-level && or ||.
func topLevelComparison(e string) (string, int) {
	depth := 0
	op, at := "", -1
	for i := 0; i < len(e); i++ {
		switch e[i] {
		case '(':
			depth++
		case ')':
			depth--
		case '\'':
			// skip a rune literal such as '(' or '\''
			j := i + 1
			if j < len(e) && e[j] == '\\' {
				j++
			}
			i = j + 1
			continue
		}
		if depth != 0 || i+1 >= len(e) {
			continue
		}
		two := e[i : i+2]
		switch {
		case two == "&&" || two == "||":
			return "", -1
		case two == "==" || two == "!=" || two == "<=" || two == ">=":
			if op != "" {
				return "", -1
			}
			op, at = two, i
			i++
		case (e[i] == '<' || e[i] == '>') && e[i+1] == ' ' && i > 0 && e[i-1] == ' ':
			if op != "" {
				return "", -1
			}
			op, at = e[i:i+1], i
		}
	}
	return op, at
}

func (g *fgen) genCallIndirect(n *wat.Sexpr) {
	var operands []*wat.Sexpr
	for _, part := range n.List[1:] {
		if !part.IsList {
			failf("call_indirect with a table or type index is unsupported")
		}
		switch part.Head() {
		case "type", "param", "result":
			if len(part.List) > 1 {
				failf("call_indirect signatures other than [] -> [] are unsupported")
			}
		default:
			operands = append(operands, part)
		}
	}
	for _, op := range operands {
		g.genInstr(op)
		if g.unreachable {
			return
		}
	}
	idx := g.pop()
	g.spill()
	g.line("table[%s](m)", g.asValue(idx))
}

func memOffset(imms []string) int {
	off := 0
	for _, imm := range imms {
		if strings.HasPrefix(imm, "offset=") {
			off = int(parseInt(imm[len("offset="):]))
		} else if !strings.HasPrefix(imm, "align=") {
			failf("unsupported memory immediate %q", imm)
		}
	}
	return off
}

func addrExpr(addr value, off int) string {
	if addr.isConst {
		return strconv.FormatUint(addr.c+uint64(off), 10)
	}
	if off == 0 {
		return trimParens(addr.expr)
	}
	return tidyExpr(fmt.Sprintf("(%s)+%d", addr.expr, off))
}

type binOp struct {
	typ    ValType
	goOp   string // infix operator, or a helper call when it starts with "rt."
	isCmp  bool
	signed bool
	fold   func(a, b uint64) uint64
}

var binOps = map[string]binOp{}

func init() {
	for _, t := range []ValType{I32, I64} {
		mask := uint64(0xffffffff)
		width := uint64(32)
		bitsName := "32"
		if t == I64 {
			mask = ^uint64(0)
			width = 64
			bitsName = "64"
		}
		sx := func(x uint64) int64 {
			if t == I32 {
				return int64(int32(uint32(x)))
			}
			return int64(x)
		}
		p := string(t) + "."
		binOps[p+"add"] = binOp{typ: t, goOp: "+", fold: func(a, b uint64) uint64 { return (a + b) & mask }}
		binOps[p+"sub"] = binOp{typ: t, goOp: "-", fold: func(a, b uint64) uint64 { return (a - b) & mask }}
		binOps[p+"mul"] = binOp{typ: t, goOp: "*", fold: func(a, b uint64) uint64 { return (a * b) & mask }}
		binOps[p+"and"] = binOp{typ: t, goOp: "&", fold: func(a, b uint64) uint64 { return a & b }}
		binOps[p+"or"] = binOp{typ: t, goOp: "|", fold: func(a, b uint64) uint64 { return a | b }}
		binOps[p+"xor"] = binOp{typ: t, goOp: "^", fold: func(a, b uint64) uint64 { return a ^ b }}
		binOps[p+"shl"] = binOp{typ: t, goOp: "<<", fold: func(a, b uint64) uint64 { return (a << (b & (width - 1))) & mask }}
		binOps[p+"shr_u"] = binOp{typ: t, goOp: ">>", fold: func(a, b uint64) uint64 { return (a & mask) >> (b & (width - 1)) }}
		binOps[p+"shr_s"] = binOp{typ: t, goOp: ">>s", signed: true, fold: func(a, b uint64) uint64 { return uint64(sx(a)>>(b&(width-1))) & mask }}
		binOps[p+"rotl"] = binOp{typ: t, goOp: "rt.Rotl" + bitsName, fold: func(a, b uint64) uint64 {
			if t == I32 {
				return uint64(bits.RotateLeft32(uint32(a), int(b&31)))
			}
			return bits.RotateLeft64(a, int(b&63))
		}}
		binOps[p+"rotr"] = binOp{typ: t, goOp: "rt.Rotr" + bitsName, fold: func(a, b uint64) uint64 {
			if t == I32 {
				return uint64(bits.RotateLeft32(uint32(a), -int(b&31)))
			}
			return bits.RotateLeft64(a, -int(b&63))
		}}
		cmp := func(op string, signed bool, f func(a, b uint64) bool) binOp {
			return binOp{typ: t, goOp: op, isCmp: true, signed: signed, fold: func(a, b uint64) uint64 { return b2u(f(a, b)) }}
		}
		binOps[p+"eq"] = cmp("==", false, func(a, b uint64) bool { return a == b })
		binOps[p+"ne"] = cmp("!=", false, func(a, b uint64) bool { return a != b })
		binOps[p+"lt_u"] = cmp("<", false, func(a, b uint64) bool { return a < b })
		binOps[p+"gt_u"] = cmp(">", false, func(a, b uint64) bool { return a > b })
		binOps[p+"le_u"] = cmp("<=", false, func(a, b uint64) bool { return a <= b })
		binOps[p+"ge_u"] = cmp(">=", false, func(a, b uint64) bool { return a >= b })
		binOps[p+"lt_s"] = cmp("<", true, func(a, b uint64) bool { return sx(a) < sx(b) })
		binOps[p+"gt_s"] = cmp(">", true, func(a, b uint64) bool { return sx(a) > sx(b) })
		binOps[p+"le_s"] = cmp("<=", true, func(a, b uint64) bool { return sx(a) <= sx(b) })
		binOps[p+"ge_s"] = cmp(">=", true, func(a, b uint64) bool { return sx(a) >= sx(b) })
	}
}

func signedType(t ValType) string {
	if t == I32 {
		return "int32"
	}
	return "int64"
}

