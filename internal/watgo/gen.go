func (g *fgen) apply(head string, imms []string) {
	if op, ok := binOps[head]; ok {
		b := g.pop()
		a := g.pop()
		g.push(g.binary(op, a, b))
		return
	}
	if helper, ok := simdBin[head]; ok {
		b := g.pop()
		a := g.pop()
		// vector operations are methods of rt.V128
		g.push(value{expr: fmt.Sprintf("%s.%s(%s)", a.expr, strings.TrimPrefix(helper, "rt."), trimParens(b.expr)), typ: V128, stable: a.stable && b.stable})
		return
	}
	if op, ok := loads[head]; ok {
		addr := g.pop()
		at := addrExpr(addr, memOffset(imms))
		if head == "i32.load8_u" || head == "i64.load8_u" {
			// a byte is an index into memory
			b := "m.Mem[" + at + "]"
			g.push(value{expr: op.typ.goType() + "(" + b + ")", typ: op.typ, byteExpr: b})
			return
		}
		g.push(value{expr: fmt.Sprintf(op.helper, "m.Mem["+at+":]"), typ: op.typ})
		return
	}
	if op, ok := stores[head]; ok {
		v := g.pop()
		addr := g.pop()
		g.spillIf(readsState)
		at := addrExpr(addr, memOffset(imms))
		if head == "i32.store8" || head == "i64.store8" {
			b := "byte(" + trimParens(g.asValue(v)) + ")"
			switch {
			case v.byteExpr != "":
				b = v.byteExpr
			case v.isConst && !v.named:
				b = byteLiteral(int(v.c & 0xff))
			}
			g.line("m.Mem[%s] = %s", at, b)
			return
		}
		g.line(op.helper, "m.Mem["+at+":]", trimParens(g.asValue(v)))
		return
	}
	switch head {
	case "i32.const", "i64.const":
		v := constValue(ValType(head[:3]), parseInt(imms[0]))
		if len(imms) > 1 {
			if name := g.consts.name(imms[1]); name != "" {
				v.expr, v.named = name, true
			}
		}
		g.push(v)
	case "v128.const":
		g.push(value{expr: v128Const(imms), typ: V128, stable: true})
	case "local.get":
		name, t := g.local(imms[0])
		g.push(value{expr: name, typ: t, isBool: g.boolLocals[name]})
	case "local.set", "local.tee":
		v := g.pop()
		name, t := g.local(imms[0])
		g.spillIf(mentions(name))
		if g.boolLocals[name] {
			if !zeroOrOne(v) {
				g.notBool[name] = true
			}
			g.line("%s = %s", name, trimParens(g.asBool(v)))
		} else {
			g.line("%s = %s", name, trimParens(g.asValue(v)))
		}
		if head == "local.tee" {
			g.push(value{expr: name, typ: t, isBool: g.boolLocals[name]})
		}
	case "global.get":
		gl := g.global(imms[0])
		if gl.Mutable {
			g.push(value{expr: "m." + gl.GoName, typ: gl.Type, isBool: g.flags[gl]})
		} else {
			g.push(constValue(gl.Type, gl.Init))
		}
	case "global.set":
		v := g.pop()
		gl := g.global(imms[0])
		g.spillIf(readsState)
		if g.flags[gl] {
			g.line("m.%s = %s", gl.GoName, trimParens(g.asBool(v)))
		} else {
			g.line("m.%s = %s", gl.GoName, trimParens(g.asValue(v)))
		}
	case "call":
		f := g.mod.FuncByRef[imms[0]]
		if f == nil {
			failf("call to unknown function %s", imms[0])
		}
		args := make([]string, len(f.Params))
		for i := len(f.Params) - 1; i >= 0; i-- {
			v := g.pop()
			if g.boolParams[f.GoName][i] {
				if !zeroOrOne(v) {
					if g.notBoolParam[f.GoName] == nil {
						g.notBoolParam[f.GoName] = map[int]bool{}
					}
					g.notBoolParam[f.GoName][i] = true
				}
				args[i] = trimParens(g.asBool(v))
				continue
			}
			args[i] = trimParens(g.asValue(v))
		}
		call := fmt.Sprintf("m.%s(%s)", f.GoName, strings.Join(args, ", "))
		isBool := g.boolFuncs[f.GoName]
		if len(f.Results) > 0 && g.pure[f.GoName] {
			// a call without side effects is an expression like a load:
			// the next write spills it
			g.push(value{expr: call, typ: f.Results[0], isBool: isBool})
			return
		}
		g.spillIf(readsState)
		if len(f.Results) > 0 {
			t := g.newTemp(f.Results[0])
			if isBool {
				g.dropTemp(t)
				t = g.newBoolTemp()
			}
			g.line("%s = %s", t, call)
			g.push(value{expr: t, typ: f.Results[0], stable: true, call: call, isBool: isBool})
		} else {
			g.line("%s", call)
		}
	case "drop":
		v := g.pop()
		// a dropped call result needs no temporary
		if v.call != "" {
			assign := strings.Repeat("\t", g.depth+1) + v.expr + " = " + v.call + "\n"
			if text := g.out.String(); strings.HasSuffix(text, assign) {
				g.out.Reset()
				g.out.WriteString(text[:len(text)-len(assign)])
				g.line("%s", v.call)
				g.dropTemp(v.expr)
			}
		}
	case "nop":
	case "unreachable":
		g.spill()
		g.line("panic(rt.Trap(\"unreachable\"))")
		g.unreachable = true
	case "return":
		if len(g.fn.Results) > 0 {
			v := g.pop()
			g.line("return %s", g.returned(v))
		} else {
			g.line("return")
		}
		g.unreachable = true
	case "br":
		l, _ := g.findLabel(imms[0])
		var v *value
		if takesValue(l) {
			x := g.pop()
			v = &x
		}
		g.emitJump(l, v)
		g.unreachable = true
	case "br_if":
		c := g.pop()
		l, _ := g.findLabel(imms[0])
		var v *value
		if takesValue(l) {
			x := g.pop()
			if !x.stable && !x.isConst {
				t := g.newTemp(x.typ)
				g.line("%s = %s", t, trimParens(g.asValue(x)))
				x = value{expr: t, typ: x.typ, stable: true}
			}
			v = &x
		}
		g.line("if %s {", trimParens(g.asBool(c)))
		g.depth++
		g.emitJump(l, v)
		g.unreachable = false
		g.depth--
		g.line("}")
		if v != nil {
			g.push(*v)
		}
	case "br_table":
		idx := g.pop()
		g.line("switch %s {", trimParens(g.asValue(idx)))
		for i, ref := range imms {
			l, _ := g.findLabel(ref)
			if takesValue(l) {
				failf("br_table with values is unsupported")
			}
			if i == len(imms)-1 {
				g.line("default:")
			} else {
				g.line("case %d:", i)
			}
			g.depth++
			g.emitJump(l, nil)
			g.unreachable = false
			g.depth--
		}
		g.line("}")
		g.unreachable = true
	case "select":
		c := g.pop()
		b := g.pop()
		a := g.pop()
		if c.isConst {
			if c.c != 0 {
				g.push(a)
			} else {
				g.push(b)
			}
			return
		}
		if a.typ == I32 && zeroOrOne(a) && zeroOrOne(b) {
			// a choice between conditions is a condition
			cond := g.asBool(c)
			var e string
			switch {
			case a.isConst && b.isConst:
				e = map[bool]string{true: cond, false: negate(cond)}[a.c == 1]
				if a.c == b.c {
					e = strconv.FormatBool(a.c == 1)
				}
			case a.isConst && a.c == 1:
				e = cond + " || " + g.asBool(b)
			case a.isConst:
				e = negate(cond) + " && " + g.asBool(b)
			case b.isConst && b.c == 1:
				e = negate(cond) + " || " + g.asBool(a)
			case b.isConst:
				e = cond + " && " + g.asBool(a)
			default:
				e = "(" + cond + " && " + g.asBool(a) + ") || (" + negate(cond) + " && " + g.asBool(b) + ")"
			}
			g.push(value{expr: "(" + e + ")", typ: I32, isBool: true, stable: a.stable && b.stable && c.stable})
			return
		}
		helper := map[ValType]string{I32: "rt.Sel32", I64: "rt.Sel64", V128: "rt.SelV"}[a.typ]
		g.push(value{expr: fmt.Sprintf("%s(%s, %s, %s)", helper, g.asBool(c), g.asValue(a), g.asValue(b)), typ: a.typ, stable: a.stable && b.stable && c.stable})
	case "i32.eqz", "i64.eqz":
		a := g.pop()
		if a.isConst {
			g.push(boolConst(a.c == 0))
			return
		}
		if a.isBool {
			g.push(value{expr: "!" + a.expr, typ: I32, isBool: true, stable: a.stable})
			return
		}
		if a.cond != "" {
			g.push(value{expr: "(" + negate(a.cond) + ")", typ: I32, isBool: true, stable: a.stable})
			return
		}
		g.push(value{expr: "(" + a.expr + " == 0)", typ: I32, isBool: true, stable: a.stable})
	case "i32.clz", "i32.ctz", "i32.popcnt", "i64.clz", "i64.ctz", "i64.popcnt":
		a := g.pop()
		t := ValType(head[:3])
		op := head[4:]
		if a.isConst {
			var r uint64
			switch {
			case t == I32 && op == "clz":
				r = uint64(bits.LeadingZeros32(uint32(a.c)))
			case t == I32 && op == "ctz":
				r = uint64(bits.TrailingZeros32(uint32(a.c)))
			case t == I32:
				r = uint64(bits.OnesCount32(uint32(a.c)))
			case op == "clz":
				r = uint64(bits.LeadingZeros64(a.c))
			case op == "ctz":
				r = uint64(bits.TrailingZeros64(a.c))
			default:
				r = uint64(bits.OnesCount64(a.c))
			}
			g.push(constValue(t, r))
			return
		}
		name := map[string]string{"clz": "LeadingZeros", "ctz": "TrailingZeros", "popcnt": "OnesCount"}[op]
		g.push(value{expr: fmt.Sprintf("%s(bits.%s%s(%s))", t.goType(), name, head[1:3], trimParens(g.asValue(a))), typ: t, stable: a.stable, clzOf: map[bool]string{true: trimParens(g.asValue(a))}[op == "clz" && t == I32]})
	case "i64.extend_i32_u":
		a := g.pop()
		if a.isConst {
			g.push(constValue(I64, a.c&0xffffffff))
			return
		}
		g.push(value{expr: "uint64(" + g.asValue(a) + ")", typ: I64, stable: a.stable})
	case "i64.extend_i32_s":
		a := g.pop()
		if a.isConst {
			g.push(constValue(I64, uint64(int64(int32(uint32(a.c))))))
			return
		}
		g.push(value{expr: "uint64(int64(int32(" + g.asValue(a) + ")))", typ: I64, stable: a.stable})
	case "i32.wrap_i64":
		a := g.pop()
		if a.isConst {
			g.push(constValue(I32, a.c))
			return
		}
		g.push(value{expr: "uint32(" + g.asValue(a) + ")", typ: I32, stable: a.stable})
	case "i8x16.splat":
		a := g.pop()
		g.push(value{expr: "rt.Splat8(" + g.asValue(a) + ")", typ: V128, stable: a.stable})
	case "i8x16.bitmask":
		a := g.pop()
		g.push(value{expr: a.expr + ".Bitmask8()", typ: I32, stable: a.stable})
	case "v128.any_true":
		a := g.pop()
		g.push(value{expr: a.expr + ".AnyTrue()", typ: I32, isBool: true, stable: a.stable})
	case "i8x16.all_true":
		a := g.pop()
		g.push(value{expr: a.expr + ".AllTrue8()", typ: I32, isBool: true, stable: a.stable})
	case "v128.not":
		a := g.pop()
		g.push(value{expr: a.expr + ".Not()", typ: V128, stable: a.stable})
	case "memory.copy":
		n := g.pop()
		src := g.pop()
		dst := g.pop()
		g.spillIf(readsState)
		// slicing past the memory or past 2^32 panics, as memory.copy traps
		dst, src = g.named(dst, "dst"), g.named(src, "src")
		g.line("copy(%s, %s)", g.memRange(dst, n), g.memRange(src, n))
	case "memory.fill":
		n := g.pop()
		v := g.pop()
		dst := g.pop()
		g.spillIf(readsState)
		if v.isConst && v.c&0xff == 0 {
			g.line("clear(%s)", g.memRange(g.named(dst, "dst"), n))
		} else {
			g.line("rt.Fill(m.Mem, %s, %s, %s)", g.asValue(dst), g.asValue(v), g.asValue(n))
		}
	case "memory.size":
		g.push(value{expr: "uint32(len(m.Mem) / rt.PageSize)", typ: I32})
	case "memory.grow":
		n := g.pop()
		g.spillIf(readsState)
		t := g.newTemp(I32)
		g.line("%s = rt.Grow(&m.Mem, %s)", t, g.asValue(n))
		g.push(value{expr: t, typ: I32, stable: true})
	default:
		failf("%s: unsupported instruction %s", g.fn.GoName, head)
	}
}

func (g *fgen) binary(op binOp, a, b value) value {
	// identities: x|0, x^0, x+0, x-0, and shifts by 0; a condition or-ed
	// with false stays a condition
	if (op.goOp == "|" || op.goOp == "^") && !op.isCmp {
		if b.isConst && b.c == 0 && a.isBool {
			return a
		}
		if a.isConst && a.c == 0 && b.isBool {
			return b
		}
	}
	if b.isConst && b.c == 0 && !op.isCmp {
		switch op.goOp {
		case "|", "^", "+", "-", "<<", ">>", ">>s", "rt.Rotl32", "rt.Rotr32", "rt.Rotl64", "rt.Rotr64":
			return g.numeric(a)
		}
	}
	if a.isConst && a.c == 0 && !op.isCmp {
		switch op.goOp {
		case "|", "^", "+":
			return g.numeric(b)
		}
	}
	// 32 - clz(x) is the bit length of x, and x ^ -1 its complement
	if op.goOp == "-" && op.typ == I32 && a.isConst && a.c == 32 && b.clzOf != "" {
		return value{expr: "uint32(bits.Len32(" + b.clzOf + "))", typ: I32, stable: b.stable}
	}
	if op.goOp == "^" && !op.isCmp && b.isConst && (b.c == 0xffffffff && op.typ == I32 || b.c == ^uint64(0) && op.typ == I64) {
		return value{expr: "^" + g.numeric(a).expr, typ: op.typ, stable: a.stable}
	}
	// x&0 is 0; operands have no side effects, calls being in temporaries
	if op.goOp == "&" && ((a.isConst && a.c == 0) || (b.isConst && b.c == 0)) {
		return constValue(op.typ, 0)
	}
	if a.isConst && b.isConst {
		r := op.fold(a.c, b.c)
		if op.isCmp {
			return boolConst(r != 0)
		}
		return constValue(op.typ, r)
	}
	stable := a.stable && b.stable
	// a constant condition decides a boolean and/or, or drops out of it
	if op.typ == I32 && (op.goOp == "&" || op.goOp == "|") && a.isConst != b.isConst {
		x, k := a, b
		if a.isConst {
			x, k = b, a
		}
		if k.c <= 1 && x.isBool {
			absorbs := (k.c != 0) == (op.goOp == "|")
			if !absorbs {
				return x
			}
			// calls are already in temporaries, so x has no side effects
			return boolConst(k.c != 0)
		}
	}
	// and/or of conditions and 0-or-1 numbers is a condition
	if op.typ == I32 && (op.goOp == "&" || op.goOp == "|") && zeroOrOne(a) && zeroOrOne(b) && !(a.isConst || b.isConst) && (!a.isBool || !b.isBool) {
		join := " && "
		if op.goOp == "|" {
			join = " || "
		}
		return value{expr: "(" + g.asBool(a) + join + g.asBool(b) + ")", typ: I32, isBool: true, stable: stable}
	}
	// a 0-or-1 value: x&1 is x, x == 1 and x != 0 are x, x == 0 is !x
	if k, x := b, a; (k.isConst && !x.isConst) || (a.isConst && !b.isConst) {
		if a.isConst {
			k, x = a, b
		}
		if zeroOrOne(x) && k.c <= 1 {
			switch {
			case op.goOp == "&" && !op.isCmp && k.c == 1:
				return x
			case op.isCmp && (op.goOp == "==") == (k.c == 1) && (op.goOp == "==" || op.goOp == "!="):
				return value{expr: "(" + g.asBool(x) + ")", typ: I32, isBool: true, stable: x.stable}
			case op.isCmp && (op.goOp == "==" || op.goOp == "!="):
				return value{expr: "(" + negate(g.asBool(x)) + ")", typ: I32, isBool: true, stable: x.stable}
			}
		}
	}
	// two 0-or-1 values compare as bools
	if op.isCmp && (op.goOp == "==" || op.goOp == "!=") && zeroOrOne(a) && zeroOrOne(b) && !a.isConst && !b.isConst {
		return value{expr: "(" + g.asBool(a) + " " + op.goOp + " " + g.asBool(b) + ")", typ: I32, isBool: true, stable: stable}
	}
	// a bool and a number: B2u(a)&x is a && x&1 != 0
	if op.typ == I32 && op.goOp == "&" && zeroOrOne(a) != zeroOrOne(b) && !a.isConst && !b.isConst {
		c, x := a, b
		if !zeroOrOne(a) {
			c, x = b, a
		}
		return value{expr: "(" + g.asValue(a) + " & " + g.asValue(b) + ")", typ: I32, stable: stable, flag: true,
			cond: "(" + g.asBool(c) + " && " + g.bit0(x) + ")"}
	}
	// x>>k & 1 is bit k of x, tested as x&(1<<k) != 0
	if op.goOp == "&" && b.isConst && b.c == 1 && !a.isBool {
		r := value{expr: "(" + g.asValue(a) + " & 1)", typ: op.typ, stable: stable, flag: true}
		switch {
		case a.bitOp != "":
			r.cond = g.bit0(a)
		case a.shrOf != nil:
			x := a.shrOf.expr
			if a.shrOf.byteExpr != "" && a.shrBy < 8 {
				x = a.shrOf.byteExpr
			}
			r.cond = fmt.Sprintf("(%s&%d != 0)", x, uint64(1)<<a.shrBy)
		case a.byteExpr != "":
			r.cond = "(" + a.byteExpr + "&1 != 0)"
		}
		return r
	}
	// boolean and/or of conditions stay boolean
	if op.typ == I32 && (op.goOp == "&" || op.goOp == "|") && a.isBool && b.isBool {
		join := " && "
		if op.goOp == "|" {
			join = " || "
		}
		return value{expr: "(" + a.expr + join + b.expr + ")", typ: I32, isBool: true, stable: stable}
	}
	av, bv := g.asValue(a), g.asValue(b)
	if op.goOp == "|" && (a.isBool || b.isBool || a.cond != "" || b.cond != "") {
		// a number from or-ing conditions tests as their ||
		return value{expr: "(" + av + " | " + bv + ")", typ: op.typ, stable: stable, cond: "(" + g.asBool(a) + " || " + g.asBool(b) + ")", bitOp: "|", lhs: &a, rhs: &b}
	}
	if op.isCmp && op.typ == I32 {
		// a byte compared with a printable constant reads as a rune literal
		if b.isConst && !b.named && isByteExpr(a.expr) {
			bv = byteLiteral(int(b.c))
		} else if a.isConst && !a.named && isByteExpr(b.expr) {
			av = byteLiteral(int(a.c))
		}
		// a loaded byte compares with a byte constant as it is
		if a.byteExpr != "" && b.isConst && !b.named && b.c <= 255 && !op.signed {
			av = a.byteExpr
		} else if b.byteExpr != "" && a.isConst && !a.named && a.c <= 255 && !op.signed {
			bv = b.byteExpr
		}
	}
	if op.isCmp {
		if op.signed {
			st := signedType(op.typ)
			side := func(v value, s string) string {
				if v.isConst && !v.named {
					// an untyped signed constant
					if op.typ == I32 {
						return strconv.FormatInt(int64(int32(uint32(v.c))), 10)
					}
					return strconv.FormatInt(int64(v.c), 10)
				}
				return st + "(" + s + ")"
			}
			return value{expr: fmt.Sprintf("(%s %s %s)", side(a, av), op.goOp, side(b, bv)), typ: I32, isBool: true, stable: stable}
		}
		return value{expr: fmt.Sprintf("(%s %s %s)", av, op.goOp, bv), typ: I32, isBool: true, stable: stable}
	}
	width := uint64(32)
	if op.typ == I64 {
		width = 64
	}
	if a.isConst && (op.goOp == "<<" || op.goOp == ">>" || op.goOp == ">>s") {
		// a constant shifted by a variable takes its type from the context,
		// which may be wider
		av = typedLiteral(op.typ, a.c)
	}
	switch op.goOp {
	case "<<", ">>":
		count := "(" + bv + " & " + strconv.FormatUint(width-1, 10) + ")"
		if b.isConst {
			count = strconv.FormatUint(b.c&(width-1), 10)
		}
		r := value{expr: fmt.Sprintf("(%s %s %s)", av, op.goOp, count), typ: op.typ, stable: stable}
		if op.goOp == ">>" && b.isConst {
			base := a
			r.shrOf, r.shrBy = &base, b.c&(width-1)
		}
		return r
	case ">>s":
		count := "(" + bv + " & " + strconv.FormatUint(width-1, 10) + ")"
		if b.isConst {
			count = strconv.FormatUint(b.c&(width-1), 10)
		}
		return value{expr: fmt.Sprintf("%s(%s(%s) >> %s)", op.typ.goType(), signedType(op.typ), av, count), typ: op.typ, stable: stable}
	}
	if rot, ok := strings.CutPrefix(op.goOp, "rt.Rot"); ok {
		// rotations are bits.RotateLeft, by a negative count to the right
		mask := width - 1
		count := "int(" + bv + "&" + strconv.FormatUint(mask, 10) + ")"
		if b.isConst {
			count = strconv.FormatUint(b.c&mask, 10)
		}
		if strings.HasPrefix(rot, "r") {
			count = "-" + count
		}
		return value{expr: fmt.Sprintf("bits.RotateLeft%d(%s, %s)", width, av, count), typ: op.typ, stable: stable}
	}
	if strings.HasPrefix(op.goOp, "rt.") {
		return value{expr: fmt.Sprintf("%s(%s, %s)", op.goOp, av, bv), typ: op.typ, stable: stable}
	}
	// and, or and xor of 0-or-1 numbers are 0 or 1
	flag := (op.goOp == "&" || op.goOp == "|" || op.goOp == "^") && zeroOrOne(a) && zeroOrOne(b)
	r := value{expr: fmt.Sprintf("(%s %s %s)", av, op.goOp, bv), typ: op.typ, stable: stable, flag: flag}
	if op.typ == I32 && (op.goOp == "&" || op.goOp == "|" || op.goOp == "^") {
		r.bitOp, r.lhs, r.rhs = op.goOp, &a, &b
	}
	return r
}

// bit0 writes the condition that bit 0 of v is set: the condition itself
// for a 0-or-1 value, and for and/or/xor the same of their operands' bits.
func (g *fgen) bit0(v value) string {
	switch {
	case zeroOrOne(v):
		return g.asBool(v)
	case v.bitOp == "|":
		return "(" + g.bit0(*v.lhs) + " || " + g.bit0(*v.rhs) + ")"
	case v.bitOp == "&":
		return "(" + g.bit0(*v.lhs) + " && " + g.bit0(*v.rhs) + ")"
	case v.bitOp == "^":
		return "(" + g.bit0(*v.lhs) + " != " + g.bit0(*v.rhs) + ")"
	case v.isConst:
		return strconv.FormatBool(v.c&1 != 0)
	case v.shrOf != nil:
		x := v.shrOf.expr
		if v.shrOf.byteExpr != "" && v.shrBy < 8 {
			x = v.shrOf.byteExpr
		}
		return fmt.Sprintf("(%s&%d != 0)", x, uint64(1)<<v.shrBy)
	}
	return "(" + v.expr + "&1 != 0)"
}

func (g *fgen) local(ref string) (string, ValType) {
	name, ok := g.localName[ref]
	if !ok {
		failf("%s: unknown local %s", g.fn.GoName, ref)
	}
	return name, g.localType[ref]
}

func (g *fgen) global(ref string) *Global {
	gl := g.mod.GlobalBy[ref]
	if gl == nil {
		failf("%s: unknown global %s", g.fn.GoName, ref)
	}
	return gl
}

func v128Const(imms []string) string {
	if len(imms) == 0 {
		failf("v128.const needs a shape")
	}
	var b [16]byte
	shape := imms[0]
	vals := imms[1:]
	lanes := map[string]int{"i8x16": 16, "i16x8": 8, "i32x4": 4, "i64x2": 2}[shape]
	if lanes == 0 || len(vals) != lanes {
		failf("unsupported v128.const %v", imms)
	}
	size := 16 / lanes
	for i, s := range vals {
		v := parseInt(s)
		for k := 0; k < size; k++ {
			b[i*size+k] = byte(v >> (8 * k))
		}
	}
	parts := make([]string, 16)
	for i, x := range b {
		parts[i] = strconv.Itoa(int(x))
	}
	return "rt.Bytes16([16]byte{" + strings.Join(parts, ", ") + "})"
}
