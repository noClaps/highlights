func (g *fgen) apply(head string, imms []string) {
	if op, ok := binOps[head]; ok {
		b := g.pop()
		a := g.pop()
		g.push(g.binary(op, a, b))
		return
	}
	if helper, ok := simdBin[head]; ok {
		b := g.pop()
		a := g.pop()
		g.push(value{expr: fmt.Sprintf("%s(%s, %s)", helper, a.expr, b.expr), typ: V128, stable: a.stable && b.stable})
		return
	}
	if op, ok := loads[head]; ok {
		addr := g.pop()
		g.push(value{expr: fmt.Sprintf("%s(m.Mem, %s)", op.helper, addrExpr(addr, memOffset(imms))), typ: op.typ})
		return
	}
	if op, ok := stores[head]; ok {
		v := g.pop()
		addr := g.pop()
		g.spill()
		g.line("%s(m.Mem, %s, %s)", op.helper, addrExpr(addr, memOffset(imms)), trimParens(g.asValue(v)))
		return
	}
	switch head {
	case "i32.const", "i64.const":
		g.push(constValue(ValType(head[:3]), parseInt(imms[0])))
	case "v128.const":
		g.push(value{expr: v128Const(imms), typ: V128, stable: true})
	case "local.get":
		name, t := g.local(imms[0])
		g.push(value{expr: name, typ: t})
	case "local.set", "local.tee":
		v := g.pop()
		name, t := g.local(imms[0])
		g.spill()
		g.line("%s = %s", name, trimParens(g.asValue(v)))
		if head == "local.tee" {
			g.push(value{expr: name, typ: t})
		}
	case "global.get":
		gl := g.global(imms[0])
		if gl.Mutable {
			g.push(value{expr: "m." + gl.GoName, typ: gl.Type})
		} else {
			g.push(constValue(gl.Type, gl.Init))
		}
	case "global.set":
		v := g.pop()
		gl := g.global(imms[0])
		g.spill()
		g.line("m.%s = %s", gl.GoName, trimParens(g.asValue(v)))
	case "call":
		f := g.mod.FuncByRef[imms[0]]
		if f == nil {
			failf("call to unknown function %s", imms[0])
		}
		args := make([]string, len(f.Params))
		for i := len(f.Params) - 1; i >= 0; i-- {
			args[i] = trimParens(g.asValue(g.pop()))
		}
		g.spill()
		call := fmt.Sprintf("m.%s(%s)", f.GoName, strings.Join(args, ", "))
		if len(f.Results) > 0 {
			t := g.newTemp(f.Results[0])
			g.line("%s = %s", t, call)
			g.push(value{expr: t, typ: f.Results[0], stable: true, call: call})
		} else {
			g.line("%s", call)
		}
	case "drop":
		v := g.pop()
		// a dropped call result needs no temporary
		if v.call != "" {
			assign := strings.Repeat("\t", g.depth+1) + v.expr + " = " + v.call + "\n"
			if text := g.out.String(); strings.HasSuffix(text, assign) {
				g.out.Reset()
				g.out.WriteString(text[:len(text)-len(assign)])
				g.line("%s", v.call)
				g.dropTemp(v.expr)
			}
		}
	case "nop":
	case "unreachable":
		g.spill()
		g.line("panic(rt.Trap(\"unreachable\"))")
		g.unreachable = true
	case "return":
		if len(g.fn.Results) > 0 {
			v := g.pop()
			g.line("return %s", trimParens(g.asValue(v)))
		} else {
			g.line("return")
		}
		g.unreachable = true
	case "br":
		l, _ := g.findLabel(imms[0])
		var v *value
		if takesValue(l) {
			x := g.pop()
			v = &x
		}
		g.emitJump(l, v)
		g.unreachable = true
	case "br_if":
		c := g.pop()
		l, _ := g.findLabel(imms[0])
		var v *value
		if takesValue(l) {
			x := g.pop()
			if !x.stable && !x.isConst {
				t := g.newTemp(x.typ)
				g.line("%s = %s", t, trimParens(g.asValue(x)))
				x = value{expr: t, typ: x.typ, stable: true}
			}
			v = &x
		}
		g.line("if %s {", trimParens(g.asBool(c)))
		g.depth++
		g.emitJump(l, v)
		g.unreachable = false
		g.depth--
		g.line("}")
		if v != nil {
			g.push(*v)
		}
	case "br_table":
		idx := g.pop()
		g.line("switch %s {", trimParens(g.asValue(idx)))
		for i, ref := range imms {
			l, _ := g.findLabel(ref)
			if takesValue(l) {
				failf("br_table with values is unsupported")
			}
			if i == len(imms)-1 {
				g.line("default:")
			} else {
				g.line("case %d:", i)
			}
			g.depth++
			g.emitJump(l, nil)
			g.unreachable = false
			g.depth--
		}
		g.line("}")
		g.unreachable = true
	case "select":
		c := g.pop()
		b := g.pop()
		a := g.pop()
		if c.isConst {
			if c.c != 0 {
				g.push(a)
			} else {
				g.push(b)
			}
			return
		}
		helper := map[ValType]string{I32: "rt.Sel32", I64: "rt.Sel64", V128: "rt.SelV"}[a.typ]
		g.push(value{expr: fmt.Sprintf("%s(%s, %s, %s)", helper, g.asBool(c), g.asValue(a), g.asValue(b)), typ: a.typ, stable: a.stable && b.stable && c.stable})
	case "i32.eqz", "i64.eqz":
		a := g.pop()
		if a.isConst {
			g.push(boolConst(a.c == 0))
			return
		}
		if a.isBool {
			g.push(value{expr: "!" + a.expr, typ: I32, isBool: true, stable: a.stable})
			return
		}
		g.push(value{expr: "(" + a.expr + " == 0)", typ: I32, isBool: true, stable: a.stable})
	case "i32.clz", "i32.ctz", "i32.popcnt", "i64.clz", "i64.ctz", "i64.popcnt":
		a := g.pop()
		t := ValType(head[:3])
		op := head[4:]
		if a.isConst {
			var r uint64
			switch {
			case t == I32 && op == "clz":
				r = uint64(bits.LeadingZeros32(uint32(a.c)))
			case t == I32 && op == "ctz":
				r = uint64(bits.TrailingZeros32(uint32(a.c)))
			case t == I32:
				r = uint64(bits.OnesCount32(uint32(a.c)))
			case op == "clz":
				r = uint64(bits.LeadingZeros64(a.c))
			case op == "ctz":
				r = uint64(bits.TrailingZeros64(a.c))
			default:
				r = uint64(bits.OnesCount64(a.c))
			}
			g.push(constValue(t, r))
			return
		}
		name := map[string]string{"clz": "Clz", "ctz": "Ctz", "popcnt": "Popcnt"}[op]
		g.push(value{expr: fmt.Sprintf("rt.%s%s(%s)", name, head[1:3], g.asValue(a)), typ: t, stable: a.stable})
	case "i64.extend_i32_u":
		a := g.pop()
		if a.isConst {
			g.push(constValue(I64, a.c&0xffffffff))
			return
		}
		g.push(value{expr: "uint64(" + g.asValue(a) + ")", typ: I64, stable: a.stable})
	case "i64.extend_i32_s":
		a := g.pop()
		if a.isConst {
			g.push(constValue(I64, uint64(int64(int32(uint32(a.c))))))
			return
		}
		g.push(value{expr: "uint64(int64(int32(" + g.asValue(a) + ")))", typ: I64, stable: a.stable})
	case "i32.wrap_i64":
		a := g.pop()
		if a.isConst {
			g.push(constValue(I32, a.c))
			return
		}
		g.push(value{expr: "uint32(" + g.asValue(a) + ")", typ: I32, stable: a.stable})
	case "i8x16.splat":
		a := g.pop()
		g.push(value{expr: "rt.Splat8(" + g.asValue(a) + ")", typ: V128, stable: a.stable})
	case "i8x16.bitmask":
		a := g.pop()
		g.push(value{expr: "rt.Bitmask8(" + a.expr + ")", typ: I32, stable: a.stable})
	case "v128.any_true":
		a := g.pop()
		g.push(value{expr: "rt.AnyTrue(" + a.expr + ")", typ: I32, isBool: true, stable: a.stable})
	case "i8x16.all_true":
		a := g.pop()
		g.push(value{expr: "rt.AllTrue8(" + a.expr + ")", typ: I32, isBool: true, stable: a.stable})
	case "v128.not":
		a := g.pop()
		g.push(value{expr: "rt.Not(" + a.expr + ")", typ: V128, stable: a.stable})
	case "memory.copy":
		n := g.pop()
		src := g.pop()
		dst := g.pop()
		g.spill()
		g.line("rt.Copy(m.Mem, %s, %s, %s)", g.asValue(dst), g.asValue(src), g.asValue(n))
	case "memory.fill":
		n := g.pop()
		v := g.pop()
		dst := g.pop()
		g.spill()
		g.line("rt.Fill(m.Mem, %s, %s, %s)", g.asValue(dst), g.asValue(v), g.asValue(n))
	case "memory.size":
		g.push(value{expr: "uint32(len(m.Mem) / rt.PageSize)", typ: I32})
	case "memory.grow":
		n := g.pop()
		g.spill()
		t := g.newTemp(I32)
		g.line("%s = rt.Grow(&m.Mem, %s)", t, g.asValue(n))
		g.push(value{expr: t, typ: I32, stable: true})
	default:
		failf("%s: unsupported instruction %s", g.fn.GoName, head)
	}
}

func (g *fgen) binary(op binOp, a, b value) value {
	// identities: x|0, x^0, x+0, x-0, and shifts by 0
	if b.isConst && b.c == 0 && !op.isCmp {
		switch op.goOp {
		case "|", "^", "+", "-", "<<", ">>", ">>s", "rt.Rotl32", "rt.Rotr32", "rt.Rotl64", "rt.Rotr64":
			return g.numeric(a)
		}
	}
	if a.isConst && a.c == 0 && !op.isCmp {
		switch op.goOp {
		case "|", "^", "+":
			return g.numeric(b)
		}
	}
	if a.isConst && b.isConst {
		r := op.fold(a.c, b.c)
		if op.isCmp {
			return boolConst(r != 0)
		}
		return constValue(op.typ, r)
	}
	stable := a.stable && b.stable
	// boolean and/or of conditions stay boolean
	if op.typ == I32 && (op.goOp == "&" || op.goOp == "|") && a.isBool && b.isBool {
		join := " && "
		if op.goOp == "|" {
			join = " || "
		}
		return value{expr: "(" + a.expr + join + b.expr + ")", typ: I32, isBool: true, stable: stable}
	}
	av, bv := g.asValue(a), g.asValue(b)
	if op.isCmp && op.typ == I32 {
		// a byte compared with a printable constant reads as a rune literal
		if b.isConst && isByteExpr(a.expr) {
			bv = byteLiteral(int(b.c))
		} else if a.isConst && isByteExpr(b.expr) {
			av = byteLiteral(int(a.c))
		}
	}
	if op.isCmp {
		if op.signed {
			st := signedType(op.typ)
			return value{expr: fmt.Sprintf("(%s(%s) %s %s(%s))", st, av, op.goOp, st, bv), typ: I32, isBool: true, stable: stable}
		}
		return value{expr: fmt.Sprintf("(%s %s %s)", av, op.goOp, bv), typ: I32, isBool: true, stable: stable}
	}
	width := uint64(32)
	if op.typ == I64 {
		width = 64
	}
	if a.isConst && (op.goOp == "<<" || op.goOp == ">>" || op.goOp == ">>s") {
		// a constant shifted by a variable takes its type from the context,
		// which may be wider
		av = typedLiteral(op.typ, a.c)
	}
	switch op.goOp {
	case "<<", ">>":
		count := "(" + bv + " & " + strconv.FormatUint(width-1, 10) + ")"
		if b.isConst {
			count = strconv.FormatUint(b.c&(width-1), 10)
		}
		return value{expr: fmt.Sprintf("(%s %s %s)", av, op.goOp, count), typ: op.typ, stable: stable}
	case ">>s":
		count := "(" + bv + " & " + strconv.FormatUint(width-1, 10) + ")"
		if b.isConst {
			count = strconv.FormatUint(b.c&(width-1), 10)
		}
		return value{expr: fmt.Sprintf("%s(%s(%s) >> %s)", op.typ.goType(), signedType(op.typ), av, count), typ: op.typ, stable: stable}
	}
	if strings.HasPrefix(op.goOp, "rt.") {
		return value{expr: fmt.Sprintf("%s(%s, %s)", op.goOp, av, bv), typ: op.typ, stable: stable}
	}
	return value{expr: fmt.Sprintf("(%s %s %s)", av, op.goOp, bv), typ: op.typ, stable: stable}
}

func (g *fgen) local(ref string) (string, ValType) {
	name, ok := g.localName[ref]
	if !ok {
		failf("%s: unknown local %s", g.fn.GoName, ref)
	}
	return name, g.localType[ref]
}

func (g *fgen) global(ref string) *Global {
	gl := g.mod.GlobalBy[ref]
	if gl == nil {
		failf("%s: unknown global %s", g.fn.GoName, ref)
	}
	return gl
}

func v128Const(imms []string) string {
	if len(imms) == 0 {
		failf("v128.const needs a shape")
	}
	var b [16]byte
	shape := imms[0]
	vals := imms[1:]
	lanes := map[string]int{"i8x16": 16, "i16x8": 8, "i32x4": 4, "i64x2": 2}[shape]
	if lanes == 0 || len(vals) != lanes {
		failf("unsupported v128.const %v", imms)
	}
	size := 16 / lanes
	for i, s := range vals {
		v := parseInt(s)
		for k := 0; k < size; k++ {
			b[i*size+k] = byte(v >> (8 * k))
		}
	}
	parts := make([]string, 16)
	for i, x := range b {
		parts[i] = strconv.Itoa(int(x))
	}
	return "rt.Bytes16([16]byte{" + strings.Join(parts, ", ") + "})"
}
