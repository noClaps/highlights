// Command genengine translates a WAT module into a Go package.
//
//	genengine -src internal/engine/wat/highlights.wat -out internal/engine -pkg engine
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"highlights/internal/wat"
	"highlights/internal/watgo"
)

func main() {
	src := flag.String("src", "", "WAT module to translate")
	out := flag.String("out", "", "output directory")
	pkg := flag.String("pkg", "engine", "package name")
	tables := flag.String("tables", "", "optional Go file for the token and language tables")
	tablesPkg := flag.String("tablespkg", "highlights", "package name of the tables file")
	flag.Parse()
	if err := run(*src, *out, *pkg, *tables, *tablesPkg); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(src, out, pkg, tables, tablesPkg string) error {
	transformed, err := wat.TransformFileWith(src, wat.Options{EnumNames: true})
	if err != nil {
		return err
	}
	if tables != "" {
		if err := writeTables(transformed, tables, tablesPkg); err != nil {
			return err
		}
	}
	mod, err := watgo.Parse(transformed.Code)
	if err != nil {
		return err
	}
	code, mem, err := watgo.Generate(mod, watgo.Options{Package: pkg, MemFile: pkg + "_mem.bin", Enums: transformed.Enums})
	if err != nil {
		return err
	}
	formatted, ferr := format.Source([]byte(code))
	if ferr != nil {
		_ = os.WriteFile(filepath.Join(out, pkg+"_gen.go.broken"), []byte(code), 0o644)
		return fmt.Errorf("format: %w", ferr)
	}
	if err := os.WriteFile(filepath.Join(out, pkg+"_gen.go"), formatted, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, pkg+"_mem.bin"), mem, 0o644)
}

func writeTables(t *wat.Transformed, path, pkg string) error {
	names, err := wat.ListTokenTypes(t.Enums)
	if err != nil {
		return err
	}
	if len(t.Languages) == 0 {
		return fmt.Errorf("no language-table found")
	}
	var sb strings.Builder
	sb.WriteString("// Code generated by internal/cmd/genengine from WAT sources. DO NOT EDIT.\n\n")
	fmt.Fprintf(&sb, "package %s\n\n", pkg)
	sb.WriteString("// TokenTypes lists the $Token names in slot order; a token ID indexes it.\n// The order is the theme-table ABI.\nvar TokenTypes = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&sb, "\t%s,\n", strconv.Quote(n))
	}
	sb.WriteString("}\n\n// languageTable lists each accepted language name and alias with its\n// lexer ID, in table order.\nvar languageTable = []languageName{\n")
	for _, l := range t.Languages {
		fmt.Fprintf(&sb, "\t{%s, %d},\n", strconv.Quote(l.Name), l.ID)
	}
	sb.WriteString("}\n")
	formatted, err := format.Source([]byte(sb.String()))
	if err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0o644)
}
